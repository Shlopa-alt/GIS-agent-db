"""Мост к базе знаний статей: литература в обоснование понятий и признаков.

У каждого понятия в `kb.concept` есть определение, написанное по рабочим
материалам проекта. Скрипт спрашивает базу знаний статей, что по этому
определению сказано в литературе, и складывает ответ черновиками: публикации —
в `kb.publication`, цитаты под понятие — в `kb.citation`. Годится ли цитата в
обоснование, решает человек в панели подтверждений.

Запуск:
    python scripts/db_kb_evidence.py                 все понятия
    python scripts/db_kb_evidence.py --сухой         показать, ничего не записывая
    python scripts/db_kb_evidence.py --понятие магматизм
    python scripts/db_kb_evidence.py --на-понятие 5  сколько статей брать на понятие

Перед запуском нужен туннель до машины базы знаний: `python scripts/kb_tunnel.py`.
Адрес — переменная `GIS_KB_URL`.

**Почему не как раньше.** Прежняя версия спрашивала у базы знаний её словарь
понятий (`/api/concept`, `/api/concepts`) и дописывала литературу в текст
обоснования паспорта признака. Ни того, ни другого больше нельзя:

* словаря понятий в базе знаний нет — знание лежит типизированным графом фактов
  и полнотекстовым поиском по фрагментам (обращения — `gisdb/kb_client`);
* все 240 паспортов признаков и все 260 связей «признак — понятие» человек уже
  подтвердил, а правило базы не даёт роли агента изменить подтверждённую или
  отклонённую строку вообще, даже один её столбец. Поэтому литература
  привязывается к понятию: от понятия к признакам ведут уже подтверждённые
  связи, и в панели цитата видна рядом с ними. Текст паспорта скрипт правит,
  только если тот всё ещё черновик — ветка осталась на случай, когда человек
  отправит паспорт на доработку.

**Откуда берутся фрагменты.** Из двух мест, и в записи видно, из какого:

* граф фактов — если у понятия есть якорь (`bridge.concept_anchor`) и в графе по
  нему есть факты. За фактом стоит цитата, проверенная кодом базы знаний: она
  есть в статье, и в ней видны оба конца связи;
* поиск по фрагментам — всегда. Он работает по всей базе и уже покрывает нашу
  тему, пока граф строится.

**Отбор — лестница.** Сначала узко: территория и метод, которым посчитаны
признаки понятия. Пусто — ослабляем: только территория, только метод, просто
понятие. Какой отбор сработал, остаётся при цитате, чтобы «по Билляхской зоне»
не путалось с «вообще по золоту».
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from gisdb import db  # noqa: E402
from gisdb import db_ingest as ingest  # noqa: E402
from gisdb import kb_client  # noqa: E402
from gisdb import kb_snapshot  # noqa: E402

СКРИПТ = "scripts/db_kb_evidence.py"

#: Территории проекта — от узкой к широкой. Имена те же, какими они названы в
#: статьях: поиск у базы знаний смысловой, но имя собственное ловит дословно.
ТЕРРИТОРИИ = ("Билляхская зона", "Анабарский щит")

#: Метод, которым посчитана группа признаков. Группы без однозначного метода
#: (gm — и гравика, и магнитка) сюда не попадают.
МЕТОД_ПО_ГРУППЕ = {
    "ast": "ASTER", "astir": "ASTER",
    "l8": "Landsat", "ls": "Landsat",
    "s2": "Sentinel-2", "s1": "Sentinel-1",
    "lin": "линеаментный анализ",
}

МЕТКА = "Литература из базы знаний статей"
ЗАГЛУШКА = re.compile(r";?\s*публикация не привязана,\s*база знаний в разработке\.?")

#: Ниже этой близости фрагмент к понятию отношения не имеет: у модели векторов
#: базы знаний текст про то же самое даёт 0,6 и выше, случайный сосед — 0,3-0,45.
БЛИЗОСТЬ = 0.55

#: Понятия в работу и группы признаков, которые к ним привязаны. Отклонённую
#: связь не подпираем литературой: человек уже решил, что признак этого не
#: измеряет, и спорить с ним через поиск незачем.
РАБОТА = """
SELECT c.code, c.definition,
       array_agg(DISTINCT f.group_code) FILTER (WHERE f.group_code IS NOT NULL) AS группы
  FROM kb.concept c
  LEFT JOIN bridge.feature_concept b
         ON b.concept_code = c.code AND b.status <> 'отклонён'
  LEFT JOIN data.feature f ON f.id = b.feature_id
 WHERE c.status <> 'отклонён'{ещё}
 GROUP BY c.code, c.definition
 ORDER BY c.code
"""

#: Только подтверждённые якоря. Подбор (scripts/db_kb_anchors.py) кладёт по
#: нескольку кандидатов на понятие черновиками; пойди мост по ним всем, в
#: литературу понятия попали бы факты о сущностях, которые человек ещё не
#: признал тем же самым.
ЯКОРЯ = """
SELECT concept_code, kb_name, relations
  FROM bridge.concept_anchor
 WHERE status = 'подтверждён' AND NOT absent AND kb_name IS NOT NULL
"""

ЧЕРНОВЫЕ_ПАСПОРТА = """
SELECT p.feature_id, p.kb_reference, b.concept_code
  FROM meta.feature_passport p
  JOIN bridge.feature_concept b ON b.feature_id = p.feature_id
 WHERE p.status = 'черновик' AND b.status <> 'отклонён'
"""


# -------------------------------------------------------------------- отбор
def варианты(территории: tuple[str, ...], метод: str | None) -> list[tuple[str | None, str | None]]:
    """Отбор от строгого к мягкому: территория и метод → территория → метод → ничего."""
    out: list[tuple[str | None, str | None]] = []
    for т in территории:
        if метод:
            out.append((т, метод))
        out.append((т, None))
    if метод:
        out.append((None, метод))
    out.append((None, None))
    return out


def запрос(код: str, определение: str | None, территория: str | None, метод: str | None) -> str:
    """Запрос к базе знаний: имя понятия, начало определения и отбор.

    Определение целиком не идёт: в нём есть оговорки про наш проект («в этом
    проекте высота даёт около половины сигнала»), и поиск уводит на статьи о
    методике обработки, а не о геологии.
    """
    куски = re.split(r"(?<=[.;])\s+", " ".join((определение or "").split()))
    смысл = " ".join(куски[:2])[:400]
    return " ".join(x for x in (код, смысл, территория, метод) if x)


def привести_находку(ф: dict, отбор: tuple[str | None, str | None]) -> dict:
    """Фрагмент поиска — к виду, в котором цитата ложится в базу."""
    территория, метод = отбор
    return {
        "doc_id": ф.get("doc_id"), "doi": ф.get("doi") or None, "title": ф.get("title"),
        "year": ф.get("year"), "url": kb_client.ссылка_на_страницу(ф),
        "authors": ф.get("authors") or [], "journal": ф.get("journal"),
        "page": kb_client.страница(ф), "quote": " ".join((ф.get("text") or "").split()),
        "similarity": ф.get("similarity"), "found_by": ф.get("found_by"),
        "verdict": None,                 # модель базы знаний этот фрагмент не смотрела
        "территория": территория, "метод": метод,
    }


def привести_факт(ц: dict, связь: str, второй: str) -> dict:
    """Цитата из графа фактов. Проверку кодом она уже прошла: цитата есть в
    статье, и в ней видны оба конца связи — это и есть её вердикт."""
    return {
        "doc_id": ц.get("doc_id"), "doi": ц.get("doi") or None, "title": ц.get("title"),
        "year": ц.get("year"), "url": kb_client.ссылка_на_страницу(ц),
        "authors": [], "journal": None,
        "page": kb_client.страница(ц), "quote": " ".join((ц.get("quote") or "").split()),
        "similarity": None, "found_by": "граф фактов",
        "verdict": f"факт графа: {связь} → {второй}",
        "территория": None, "метод": None,
    }


def упоминает(ф: dict, территория: str) -> bool:
    """Правда ли фрагмент про эту территорию, а не просто похож по смыслу.

    Поиск у базы знаний смысловой: слово «Билляхская» в запросе ничего не
    отсекает, оно лишь двигает ранжирование. Первый же прогон это и показал —
    под отбором «Билляхская зона» пришли статьи про Египет и Кот-д'Ивуар.
    Поэтому отбор по территории считается сработавшим, только если имя
    территории есть в самом фрагменте или в названии статьи. Сравниваем по
    основе слова: в статьях встречается и «Билляхской», и «Билляхская».
    """
    основа = территория.split()[0][:6].lower()
    текст = " ".join(str(ф.get(п) or "") for п in ("text", "title")).lower()
    return основа in текст


def из_поиска(знания, код: str, определение, метод, территории, сколько: int) -> list[dict]:
    """Фрагменты по понятию: лестница отбора до первого непустого ответа."""
    for отбор in варианты(территории, метод):
        территория, _ = отбор
        найдено = знания.поиск(
            запрос(код, определение, *отбор),
            предел=сколько, на_статью=1, мин_близость=БЛИЗОСТЬ,
        )
        if территория:
            найдено = [ф for ф in найдено if упоминает(ф, территория)]
        if найдено:
            return [привести_находку(ф, отбор) for ф in найдено]
    return []


def из_графа(знания, якоря: list[str], связи: set[str], сколько: int) -> list[dict]:
    """Факты графа по якорям понятия. Нет якоря или фактов — пустой список, и это
    не сбой: граф у них строится, и наши имена в него ещё не пришли."""
    цитаты: list[dict] = []
    for имя in якоря:
        try:
            датасет = знания.датасет(имя)
        except kb_client.НетЯкоря:
            continue
        for связь in датасет.get("facts") or []:
            if связи and связь.get("relation") not in связи:
                continue
            for ц in связь.get("quotes") or []:
                цитаты.append(привести_факт(ц, связь["relation"], связь["other"]))
                if len(цитаты) >= сколько:
                    return цитаты
    return цитаты


# --------------------------------------------------------- текст обоснования
def без_старого_блока(текст: str | None) -> str:
    """Снять прежний блок литературы и заглушку «публикация не привязана»."""
    чистый = ЗАГЛУШКА.sub("", текст or "")
    return чистый.split(МЕТКА)[0].strip().rstrip(";").strip()


def ссылка(ц: dict) -> str:
    авторы = ц.get("authors") or []
    кто = (авторы[0] + (" и др." if len(авторы) > 1 else "")) if авторы else ""
    год = f", {ц['year']}" if ц.get("year") else ""
    страница = f", с. {ц['page']}" if ц.get("page") else ""
    адрес = f"doi:{ц['doi']}" if ц.get("doi") else (ц.get("url") or "")
    цитата = ц["quote"] if len(ц["quote"]) <= 300 else ц["quote"][:297].rsplit(" ", 1)[0] + "…"
    return f"{кто}{' ' if кто else ''}{ц.get('title') or ''}{год}{страница} — {адрес}: «{цитата}»"


def блок(ответы: list[dict]) -> str:
    """Блок литературы в том виде, в каком его читает человек."""
    строки = [f"{МЕТКА} (черновик, проверяет человек):"]
    for о in ответы:
        отбор = ", ".join(x for x in (о.get("территория"), о.get("метод")) if x)
        откуда = о.get("откуда") or "поиск по фрагментам"
        строки.append(f"— {о['понятие']} [{откуда}"
                      f"{'; ' + отбор if отбор else '; без отбора по территории и методу'}]:")
        if not о["фрагменты"]:
            строки.append("    в статьях базы знаний ничего не нашлось")
            continue
        for ц in о["фрагменты"]:
            строки.append("    " + ссылка(ц))
    return "\n".join(строки)


# ------------------------------------------------------------------- запись
def записать_публикацию(conn, ц: dict) -> int:
    return conn.execute(
        """INSERT INTO kb.publication (kb_doc_id, doi, title, year, url, authors, journal)
           VALUES (%s, %s, %s, %s, %s, %s, %s)
           ON CONFLICT (kb_doc_id) DO UPDATE SET
               doi = coalesce(EXCLUDED.doi, kb.publication.doi),
               title = coalesce(EXCLUDED.title, kb.publication.title),
               year = coalesce(EXCLUDED.year, kb.publication.year),
               url = coalesce(EXCLUDED.url, kb.publication.url)
           RETURNING id""",
        (ц["doc_id"], ц.get("doi"), ц.get("title"), ц.get("year"), ц.get("url"),
         ц.get("authors") or [], ц.get("journal")),
    ).fetchone()[0]


def записать_цитату(conn, run_id: int, публикация: int, понятие: str, ц: dict, as_of) -> None:
    """Новая цитата — черновиком; известная обновляется, пока она черновик."""
    conn.execute(
        """INSERT INTO kb.citation (publication_id, concept_code, quote, page, territory,
                                    method, kb_similarity, kb_found_by, kb_verdict, kb_as_of,
                                    run_id)
           VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
           ON CONFLICT (publication_id, concept_code, quote_hash) DO UPDATE SET
               kb_similarity = EXCLUDED.kb_similarity, kb_found_by = EXCLUDED.kb_found_by,
               kb_verdict = EXCLUDED.kb_verdict, kb_as_of = EXCLUDED.kb_as_of,
               run_id = EXCLUDED.run_id
           WHERE kb.citation.status = 'черновик'""",
        (публикация, понятие, ц["quote"], ц.get("page"), ц.get("территория"), ц.get("метод"),
         ц.get("similarity"), ц.get("found_by"), ц.get("verdict"), as_of, run_id),
    )


def записать_операцию(conn, run_id: int, адрес: str) -> int:
    """Операция прогона: чем и откуда взята литература.

    Рёбер в `meta.derivation` при этом не пишется, хотя напрашивается. Во-первых,
    ограничение `derivation_kinds` знает виды «файл, слой, признак, паспорт,
    публикация» — понятия среди них нет, и это верно: понятие не получено
    операцией из данных, оно взято из предметных материалов и обосновано
    литературой. Во-вторых, ребро «публикация → понятие» уже есть — это сама
    строка `kb.citation`: в ней и публикация, и понятие, и номер прогона.
    """
    return conn.execute(
        """INSERT INTO meta.operation (kind, script, git_commit, params, run_id)
           VALUES ('обоснование из литературы', %s, %s, %s, %s) RETURNING id""",
        (СКРИПТ, ingest.git_commit(),
         json.dumps({"база знаний": адрес}, ensure_ascii=False), run_id),
    ).fetchone()[0]


def собрать(знания, строки: list, якоря: dict, связи: dict, сколько: int) -> list[dict]:
    """По каждому понятию — цитаты: сперва граф, если он его знает, иначе поиск."""
    ответы: list[dict] = []
    for код, определение, группы in строки:
        метод = next((МЕТОД_ПО_ГРУППЕ[г] for г in (группы or []) if г in МЕТОД_ПО_ГРУППЕ), None)
        фрагменты = из_графа(знания, якоря.get(код, []), связи.get(код, set()), сколько)
        откуда = "граф фактов"
        if not фрагменты:
            фрагменты = из_поиска(знания, код, определение, метод, ТЕРРИТОРИИ, сколько)
            откуда = "поиск по фрагментам"
        первый = фрагменты[0] if фрагменты else {}
        ответы.append({
            "понятие": код, "метод": первый.get("метод"), "территория": первый.get("территория"),
            "откуда": откуда, "фрагменты": фрагменты,
        })
    return ответы


# ---------------------------------------------------------------------- ход
def main(аргументы: list[str] | None = None) -> int:
    разбор = argparse.ArgumentParser(description="Литература из базы знаний под понятия")
    разбор.add_argument("--сухой", action="store_true", help="показать, ничего не записывая")
    разбор.add_argument("--понятие", default=None, help="только одно понятие")
    разбор.add_argument("--на-понятие", type=int, default=3, help="сколько статей на понятие")
    разбор.add_argument("--адрес", default=kb_client.АДРЕС)
    ключи = разбор.parse_args(аргументы)

    знания = kb_client.БазаЗнаний(ключи.адрес)
    try:
        состояние = знания.состояние()
    except kb_client.НетСвязи as сбой:
        print(сбой, file=sys.stderr)
        return 1
    print(f"база знаний {ключи.адрес}: статей {состояние['статей']}, "
          f"фрагментов {состояние['фрагментов']}, фактов в графе {состояние['фактов']}, "
          f"версия {состояние['версия'] or 'неизвестна'}")

    with db.connect("gis_agent") as conn:
        строки = conn.execute(
            РАБОТА.format(ещё=" AND c.code = %s" if ключи.понятие else ""),
            (ключи.понятие,) if ключи.понятие else (),
        ).fetchall()
        if not строки:
            print("понятий для работы нет", file=sys.stderr)
            return 1

        якоря: dict[str, list[str]] = {}
        связи: dict[str, set[str]] = {}
        for код, имя, перечень in conn.execute(ЯКОРЯ).fetchall():
            якоря.setdefault(код, []).append(имя)
            связи.setdefault(код, set()).update(перечень or [])
        if not якоря:
            print("якорей в графе пока нет — работаем поиском по фрагментам")

        ответы = собрать(знания, строки, якоря, связи, ключи.на_понятие)
        for о in ответы:
            отбор = ", ".join(x for x in (о["территория"], о["метод"]) if x)
            print(f"  {о['понятие']}: статей {len(о['фрагменты'])} "
                  f"({о['откуда']}{'; ' + отбор if отбор else ''})")
        for пометка in знания.пометки:
            print(f"  неполно: {пометка}")

        if ключи.сухой:
            print("\n" + блок(ответы))
            print(f"\nсухой прогон: цитат к записи "
                  f"{sum(len(о['фрагменты']) for о in ответы)}, ничего не записано")
            return 0

        всего = 0
        with ingest.run(conn, script=СКРИПТ,
                        note=f"литература по {len(ответы)} понятиям") as run_id:
            прошлый = kb_snapshot.записать(conn, состояние, СКРИПТ, run_id)
            print("  " + kb_snapshot.сравнение(прошлый, состояние))
            публикации: dict[str, int] = {}
            for о in ответы:
                for ц in о["фрагменты"]:
                    if ц["doc_id"] not in публикации:
                        публикации[ц["doc_id"]] = записать_публикацию(conn, ц)
                    записать_цитату(conn, run_id, публикации[ц["doc_id"]], о["понятие"], ц,
                                    состояние.get("проверено"))
                    всего += 1
            записать_операцию(conn, run_id, ключи.адрес)

            # Текст обоснования правим только у черновиков паспортов: менять
            # подтверждённое человеком правило базы не даёт, и это правильно.
            обновлено = 0
            for feature_id, обоснование, код in conn.execute(ЧЕРНОВЫЕ_ПАСПОРТА).fetchall():
                свои = [о for о in ответы if о["понятие"] == код]
                if not свои:
                    continue
                текст = без_старого_блока(обоснование)
                обновлено += conn.execute(
                    """UPDATE meta.feature_passport SET kb_reference = %s
                        WHERE feature_id = %s AND status = 'черновик'""",
                    ((текст + "\n\n" if текст else "") + блок(свои), feature_id),
                ).rowcount

            ingest.add_metric(conn, run_id, "публикаций", len(публикации))
            ingest.add_metric(conn, run_id, "цитат", всего)
            ingest.add_metric(conn, run_id, "паспортов обновлено", обновлено)
            conn.commit()
            print(f"\nзаписано: публикаций {len(публикации)}, цитат {всего}, "
                  f"паспортов обновлено {обновлено}; прогон #{run_id}")
            print("дальше — панель подтверждений: цитаты ждут человека")
    return 0


