#: Правила вместо перечисления: признаков этого рода десятки, и список кодов в
#: коде пришлось бы править после каждого пересчёта признаков.
ПРАВИЛА = {
    "разброс": lambda код: код.endswith("_std"),
    "сырой канал": lambda код: (
        not код.endswith("_std")
        and (re.search(r"_b\d", код) is not None
             or any(часть in код for часть in ("_ch", "_blue", "_green", "_red", "_swir")))
    ),
}

#: Признаки, у которых подтверждённая связь ведёт к одному фактору, а словарь
#: прямо называет другой. Такое расхождение нельзя ни исправить скриптом
#: (связь подтверждена человеком, и правило базы не даст её переписать), ни
#: оставить молча. Поэтому связь с нужным критерием предлагается черновиком, а
#: решение остаётся человеку — вместе с цитатой из словаря, по которой видно,
#: откуда предложение.
ПРЕДЛОЖЕНИЯ: tuple[tuple[str, str, str], ...] = (
    ("dem_incision", "погребённая палеодолина",
     "словарь: «прямой маркер погребённых палеодолин — ключевой признак фактора "
     "„долины и впадины“ генетической модели»; подтверждённая связь ведёт к рельефу"),
    ("relief2_catch_log", "погребённая палеодолина",
     "словарь: «положение в современной гидросети — косвенный индикатор "
     "унаследованной палеодолинной сети»; подтверждённая связь ведёт к "
     "гидротермальным изменениям"),
    ("s2_iron_ox", "зона окисления сульфидов",
     "словарь: «маркер зоны окисления сульфидов (gossan) — часто сопровождает выходы "
     "рудных тел на поверхность»; подтверждённая связь ведёт к обнажённости"),
)

СВЯЗИ_ФАКТОРОВ = """
SELECT b.feature_id, f.code, b.concept_code, b.role
  FROM bridge.feature_concept b
  JOIN data.feature f ON f.id = b.feature_id
  JOIN kb.concept c ON c.code = b.concept_code
 WHERE b.status = 'подтверждён' AND c.kind <> 'критерий'
"""


def есть_уровни(conn) -> bool:
    return bool(conn.execute(
        """SELECT count(*) FROM information_schema.columns
            WHERE table_schema = 'kb' AND table_name = 'concept'
              AND column_name = 'parent_code'"""
    ).fetchone()[0])


def подходит(критерий: dict, код: str) -> bool:
    if код in критерий["признаки"]:
        return True
    правило = критерий["правило"]
    return bool(правило) and ПРАВИЛА[правило](код)


def разобрать(conn, отбор: str | None) -> tuple[list[dict], list[tuple], list[str]]:
    """Какие критерии заводить, какие связи ставить и что осталось без критерия."""
    критерии = [к for к in КРИТЕРИИ if not отбор or к["фактор"] == отбор]
    по_фактору: dict[str, list[dict]] = {}
    for к in критерии:
        по_фактору.setdefault(к["фактор"], []).append(к)

    заведены = {к["код"] for к in критерии}
    предложено: dict[str, list[tuple[str, str]]] = {}
    for код, критерий, почему in ПРЕДЛОЖЕНИЯ:
        if критерий in заведены:
            предложено.setdefault(код, []).append((критерий, почему))

    связи: list[tuple] = []
    без: set[str] = set()
    for feature_id, код, фактор, роль in conn.execute(СВЯЗИ_ФАКТОРОВ).fetchall():
        for критерий, почему in предложено.get(код, ()):
            связи.append((feature_id, критерий, роль, почему))
        свои = по_фактору.get(фактор)
        if свои is None:
            continue                      # фактор не в этом прогоне
        нашлись = [к for к in свои if подходит(к, код)]
        if нашлись:
            for к in нашлись:
                связи.append((feature_id, к["код"], роль, к["источник"]))
        elif код not in предложено:
            без.add(f"{код} ({фактор})")
    return критерии, связи, sorted(без)


def записать_критерий(conn, к: dict) -> None:
    определение = к["определение"]
    conn.execute(
        """INSERT INTO kb.concept (code, kind, definition, source, parent_code)
           VALUES (%s, 'критерий', %s, %s, %s)
           ON CONFLICT (code) DO UPDATE
               SET definition = EXCLUDED.definition,
                   source = EXCLUDED.source,
                   parent_code = EXCLUDED.parent_code
             WHERE kb.concept.status = 'черновик'""",
        (к["код"], определение, к["источник"], к["фактор"]),
    )


def записать_связь(conn, run_id: int, feature_id: int, критерий: str,
                   роль: str | None, источник: str) -> None:
    # `origin` закрытый список из двух значений: материал ВНИГНИ и литература по
    # зоне — «внешняя публикация», наш словарь и наши измерения — «наш результат».
    откуда = "внешняя публикация" if ВНИГНИ in источник or ЗОНА in источник else "наш результат"
    conn.execute(
        """INSERT INTO bridge.feature_concept
               (feature_id, concept_code, role, origin, evidence_ref, run_id)
           VALUES (%s, %s, %s, %s, %s, %s)
           ON CONFLICT (feature_id, concept_code) DO UPDATE
               SET role = EXCLUDED.role, evidence_ref = EXCLUDED.evidence_ref,
                   run_id = EXCLUDED.run_id
             WHERE bridge.feature_concept.status = 'черновик'""",
        (feature_id, критерий, роль, откуда, источник, run_id),
    )


def main(аргументы: list[str] | None = None) -> int:
    разбор = argparse.ArgumentParser(description="Критерии предметной модели")
    разбор.add_argument("--сухой", action="store_true",
                        help="показать, ничего не записывая")
    разбор.add_argument("--фактор", default=None, help="только под одним фактором")
    ключи = разбор.parse_args(аргументы)

    with db.connect("gis_agent") as conn:
        if not есть_уровни(conn):
            print("в базе нет уровней предметной модели: накатите "
                  "db/sql/018_concept_level.sql (python db/migrate.py)", file=sys.stderr)
            return 1

        известные = {к for (к,) in conn.execute(
            """SELECT code FROM kb.concept
                WHERE kind IN ('рудоконтролирующий фактор', 'условие наблюдения')"""
        ).fetchall()}
        чужие = sorted({к["фактор"] for к in КРИТЕРИИ} - известные)
        if чужие:
            print(f"в базе нет таких факторов: {', '.join(чужие)}", file=sys.stderr)
            return 1

        критерии, связи, без = разобрать(conn, ключи.фактор)
        if not критерии:
            print(f"под фактором «{ключи.фактор}» критериев не описано", file=sys.stderr)
            return 1

        фактор = None
        for к in критерии:
            if к["фактор"] != фактор:
                фактор = к["фактор"]
                print(f"\n{фактор}")
            сколько = len({с[0] for с in связи if с[1] == к["код"]})
            print(f"  {к['код']:46} признаков {сколько}")

        print(f"\nкритериев {len(критерии)}, связей «признак — критерий» {len(связи)}")
        if без:
            print(f"без критерия остаются {len(без)}: {', '.join(без)}")
            print("это не сбой: придуманный критерий хуже видимого пробела")

        if ключи.сухой:
            print("\nсухой прогон: ничего не записано")
            return 0

        with ingest.run(conn, script=СКРИПТ,
                        note=f"критерии предметной модели: {len(критерии)}") as run_id:
            for к in критерии:
                записать_критерий(conn, к)
            for feature_id, критерий, роль, источник in связи:
                записать_связь(conn, run_id, feature_id, критерий, роль, источник)
            ingest.add_metric(conn, run_id, "критериев", len(критерии))
            ingest.add_metric(conn, run_id, "связей признак-критерий", len(связи))
            ingest.add_metric(conn, run_id, "признаков без критерия", len(без))
            conn.commit()

        осталось = conn.execute(
            """SELECT чего_нет, count(*) FROM kb.concept_gap
                GROUP BY 1 ORDER BY 2 DESC"""
        ).fetchall()
        print(f"\nзаписано черновиками, прогон #{run_id}")
        print("пробелы модели после загрузки:")
        for чего, сколько in осталось:
            print(f"  {чего:30} {сколько}")
        print("\nдальше — панель подтверждений: критерии и связи ждут человека")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
