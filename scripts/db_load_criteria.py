"""Критерии предметной модели: средний уровень между фактором и признаком.

Зачем. После миграции 018 в модели есть этапы, факторы и признаки, а уровня
«критерий» нет ни одного: `kb.concept_gap` говорит «218 признаков без критерия».
Без него объяснение участка карты не складывается — на восьми факторах висят все
связи, и половина на «обнажённости и растительном покрове», которая к оруднению
не относится вовсе. Ответ «эта клетка перспективна из-за обнажённости» не
объясняет ничего.

Критерий отвечает за **одну проверяемую вещь**: не «гидротермальные изменения»
вообще, а серицит-мусковитовая изменённость, каолинитизация и зона окисления
сульфидов по отдельности — у них разная температура, разная стадия процесса и, как
выяснилось на этом датасете, совершенно разный вклад в прогноз.

Откуда берутся определения. Из трёх источников, и у каждого критерия сказано, из
какого:

* словарь признаков проекта (`meta.feature_term`) — техническое описание и
  формулировка эксперта: что именно измеряет признак;
* генетическая схема наследования и перераспределения золота (ВНИГНИ, версия 2
  от 21.10.2026) — на каком этапе процесса эта вещь появляется;
* рабочие материалы по Билляхской и Хаптасыннахской зонам — две стадии
  изменений, pathfinder-минералогия, структурный контроль.

**Языковую модель здесь не спрашиваем.** Критерий — основание всех будущих
объяснений карты; слабая модель на нём домыслит физику, и домысел уйдёт в
подтверждённое знание базы. Паспорта признаков агент пишет сам, а критерии
пишутся из материалов и подтверждаются человеком.

Как ставятся связи «признак — критерий». Не заново: берутся **уже подтверждённые**
связи «признак — фактор», и если код признака входит в критерий под этим же
фактором, заводится черновик связи с критерием и с той же ролью (прокси или
прямой). Поэтому скрипт не может привязать признак к критерию под чужим фактором
и не заводит связей для устаревших версий признака.

Признак, которому критерия не нашлось, остаётся без критерия — и виден в
`kb.concept_gap`. Это лучше придуманного критерия: пробел, который видно
запросом, честнее полного дерева, половина которого выдумана.

    python scripts/db_load_criteria.py --сухой      показать, ничего не записывая
    python scripts/db_load_criteria.py
    python scripts/db_load_criteria.py --фактор магматизм
"""

