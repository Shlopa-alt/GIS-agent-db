"""Обмен с базой знаний файлами: двусторонний обмен при односторонней связи.

Соединение всегда одно и наше — мы ходим к базе знаний, она к нам никогда: в
этой базе закрытые материалы организации (34 слоя из 40 распространять
нельзя), и слушающий порт у нас снял бы защиту, выстроенную второй волной.
Данные при этом идут в обе стороны — файлами по тому же туннелю SSH.

Наружу уходят два файла:

* `вердикты.json` — что человек решил по цитатам и якорям, с причиной отказа.
  Отклонённая цитата — отрицательный пример для отбора базы знаний, принятая —
  положительный. Здесь же — первый замер нашего порога близости 0,55 по
  решениям человека, а не на глаз;
* `темы-gis.yaml` — чего мы ищем, в формате тем добычи самой базы знаний
  (`config/topics.yaml`, `python georag.py all --topics …`): пробелы в данных,
  которые закрываются хотя бы литературой, понятия без якоря в графе и наша
  территория. Формат её же — значит, файл можно пустить в добычу без
  переделки.

Чего наружу не уходит никогда: значений признаков, слоёв, паспортов, путей к
файлам. Только решения по литературе и названия тем.

Запуск:
    python scripts/kb_exchange.py                  собрать файлы локально
    python scripts/kb_exchange.py --отправить      и положить на машину базы знаний
    python scripts/kb_exchange.py --забрать        забрать ответ с той стороны

Каталог на той машине — переменная `GIS_KB_EXCHANGE` (например
`C:/projects/BZ/.local/exchange/gis`). Пока место не согласовано с владельцем
базы знаний, отправка отказывает: класть файлы в чужую систему наугад нельзя.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import statistics
import subprocess
import sys
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from gisdb import db  # noqa: E402
from gisdb import db_ingest as ingest  # noqa: E402

СКРИПТ = "scripts/kb_exchange.py"
МАШИНА = os.environ.get("GIS_KB_HOST", "kb")
КАТАЛОГ_ТАМ = os.environ.get("GIS_KB_EXCHANGE")
ЗДЕСЬ = db.ROOT / "обмен"

#: Порог близости моста (scripts/db_kb_evidence.py, БЛИЗОСТЬ). Повторён здесь,
#: потому что замер идёт именно против него.
ПОРОГ = 0.55

#: Пробелы в данных, которые литература хотя бы частично закрывает: статьи о
#: том, как это проявлено на нашей или похожей площади. Пробел покрытия съёмки
#: (`aster-вне-контура`) статьёй не закрывается — его здесь нет намеренно.
ТЕМЫ_ПРОБЕЛОВ: dict[str, tuple[str, ...]] = {
    "agsm-k-eu-eth": (
        "аэрогамма-спектрометрия калиевый метасоматоз золото",
        "airborne gamma-ray spectrometry potassium gold",
    ),
    "geochem-au-ореолы": (
        "геохимические ореолы золота", "шлиховые ореолы золота",
        "gold geochemical halo", "heavy mineral concentrate gold",
    ),
    "geochem-pathfinder": (
        "элементы-спутники золота мышьяк сурьма", "gold pathfinder elements arsenic antimony",
    ),
}

#: Наша территория — темы, по которым корпус должен расти в первую очередь:
#: в первом прогоне моста привязка к площади нашлась у 4 понятий из 8 и вся —
#: из одной статьи.
ТЕМЫ_ТЕРРИТОРИИ = (
    "Анабарский щит золото", "Anabar shield gold",
    "Билляхская зона", "Хаптасыннахская рудная зона",
    "Котуйкан-Монхолинская зона", "Anabar shield Riphean gold",
)

ВЕРДИКТЫ_ЦИТАТ = """
SELECT ц.id, ц.concept_code, ц.status::text, п.kb_doc_id, п.doi, п.title, ц.page,
       ц.quote_hash, ц.kb_similarity, ц.kb_found_by, ц.territory, ц.method, ц.kb_as_of,
       (SELECT r.comment FROM meta.review r
         WHERE r.object_kind = 'цитата' AND r.object_id = ц.id
         ORDER BY r.at DESC LIMIT 1) AS причина
  FROM kb.citation ц
  JOIN kb.publication п ON п.id = ц.publication_id
 WHERE ц.status IN ('подтверждён', 'отклонён')
 ORDER BY ц.id
"""

ВЕРДИКТЫ_ЯКОРЕЙ = """
SELECT я.concept_code, я.kb_name, я.absent, я.status::text, я.relations,
       (SELECT r.comment FROM meta.review r
         WHERE r.object_kind = 'якорь понятия' AND r.object_id = я.id
         ORDER BY r.at DESC LIMIT 1) AS причина
  FROM bridge.concept_anchor я
 WHERE я.status IN ('подтверждён', 'отклонён')
 ORDER BY я.concept_code, я.id
"""

БЕЗ_ЯКОРЯ = """
SELECT c.code
  FROM kb.concept c
 WHERE c.status <> 'отклонён' AND c.kind <> 'критерий'
   AND NOT EXISTS (SELECT 1 FROM bridge.concept_anchor я
                    WHERE я.concept_code = c.code AND NOT я.absent
                      AND я.status <> 'отклонён')
 ORDER BY c.code
"""


# --------------------------------------------------------------------- замер
def замер_порога(цитаты: list[dict], порог: float = ПОРОГ) -> dict:
    """Что решения человека говорят о пороге близости.

    Порог подобран на глаз: «про то же самое — 0,6 и выше, случайный сосед —
    0,3-0,45». Решения дают первую проверку: если отклонённые лежат так же
    высоко, как принятые, близость векторов не отделяет годное от чужого, и
    поднимать порог бесполезно — нужен другой отбор.
    """
    def ряд(статус: str) -> list[float]:
        return sorted(ц["близость"] for ц in цитаты
                      if ц["статус"] == статус and ц["близость"] is not None)

    принято, отклонено = ряд("подтверждён"), ряд("отклонён")
    if not принято and not отклонено:
        return {"вывод": "мерить нечего: по цитатам нет ни одного решения человека"}

    def описание(р: list[float]) -> dict:
        return ({"сколько": len(р), "мин": р[0], "медиана": statistics.median(р), "макс": р[-1]}
                if р else {"сколько": 0})

    out = {"порог": порог, "принято": описание(принято), "отклонено": описание(отклонено)}
    if принято and отклонено:
        # Доля пар «принятая выше отклонённой» — та же площадь под кривой, но
        # читается без определения: 0,5 — близость не различает, 1 — различает всегда.
        выше = sum((п > о) + 0.5 * (п == о) for п in принято for о in отклонено)
        out["различение"] = round(выше / (len(принято) * len(отклонено)), 3)
        out["вывод"] = (
            "близость различает годное и чужое" if out["различение"] >= 0.75 else
            "близость почти не различает годное и чужое — порог не главный рычаг"
        )
    else:
        out["вывод"] = "решения только одного рода — различение не измерить"
    return out


# ------------------------------------------------------------------- сборка
def вердикты(conn) -> dict:
    столбцы = ("id", "понятие", "статус", "doc_id", "doi", "статья", "страница",
               "отпечаток_цитаты", "близость", "чем_нашлось", "территория", "метод",
               "разметка_от", "причина")
    цитаты = [dict(zip(столбцы, с)) for с in conn.execute(ВЕРДИКТЫ_ЦИТАТ).fetchall()]
    for ц in цитаты:
        if ц["разметка_от"] is not None:
            ц["разметка_от"] = ц["разметка_от"].isoformat()
    якоря = [dict(zip(("понятие", "сущность", "в_графе_нет", "статус", "связи", "причина"), с))
             for с in conn.execute(ВЕРДИКТЫ_ЯКОРЕЙ).fetchall()]
    return {
        "что_это": ("Решения человека по литературе, которую принесла база знаний: "
                    "принятые и отклонённые цитаты и якоря понятий. Отклонённое — "
                    "отрицательный пример для отбора, принятое — положительный."),
        "собрано": datetime.now().astimezone().isoformat(timespec="seconds"),
        "цитаты": цитаты,
        "якоря": якоря,
        "замер_порога": замер_порога(цитаты),
    }


def _кавычки(текст: str) -> str:
    """Так же, как кавычит темы сама база знаний (graph/gaps.py, _quote)."""
    if any(з in текст for з in ':#[]{},&*!|>\'"%@`') or текст != текст.strip():
        return '"' + текст.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return текст


def темы(conn) -> str:
    """Файл тем добычи в формате базы знаний: комментарий-причина и темы списком."""
    пробелы = {код: (название, доступ) for код, название, доступ in conn.execute(
        "SELECT code, title, access FROM meta.gap ORDER BY priority, code").fetchall()}
    без_якоря = [к for (к,) in conn.execute(БЕЗ_ЯКОРЯ).fetchall()]
    строки = [
        "# ТЕМЫ ОТ БАЗЫ ДАННЫХ ПРОЕКТА ПРОГНОЗА — собраны scripts/kb_exchange.py,",
        "# пересоздаются им же. Формат тот же, что у config/topics.yaml.",
        "#",
        "# Добыть:  python georag.py all --topics темы-gis.yaml",
        "",
        "topics:",
    ]
    for код, темы_ in ТЕМЫ_ПРОБЕЛОВ.items():
        if код not in пробелы:
            continue
        название, доступ = пробелы[код]
        строки.append(f"  # пробел в данных «{название}» (доступ: {доступ}) — "
                      "нужны статьи о том, как это проявлено")
        строки += [f"  - {_кавычки(т)}" for т in темы_]
    строки.append("  # наша территория: привязка к площади пока из одной статьи")
    строки += [f"  - {_кавычки(т)}" for т in ТЕМЫ_ТЕРРИТОРИИ]
    for код in без_якоря:
        строки.append(f"  # понятие без якоря в графе: «{код}»")
        строки.append(f"  - {_кавычки(тема_понятия(код))}")
    return "\n".join(строки) + "\n"


def тема_понятия(код: str) -> str:
    """Понятие — в тему добычи: без номера этапа и с привязкой к золоту.

    «этап I: архей — ранний протерозой» поисковику статей ничего не говорит, а
    просто «магматизм» принесёт статьи обо всём магматизме сразу.
    """
    return f"{re.sub(r'^этап [IVX]+:\s*', '', код)} золото"


# ------------------------------------------------------------------ перенос
def scp(откуда: str, куда: str) -> None:
    """Копия по тому же ключу и той же записи `kb`, что и туннель."""
    subprocess.run(["scp", "-q", "-r", откуда, куда], check=True)


def main(аргументы: list[str] | None = None) -> int:
    разбор = argparse.ArgumentParser(description="Обмен файлами с базой знаний")
    разбор.add_argument("--отправить", action="store_true",
                        help="положить собранное на машину базы знаний")
    разбор.add_argument("--забрать", action="store_true",
                        help="забрать ответ с машины базы знаний")
    ключи = разбор.parse_args(аргументы)

    if (ключи.отправить or ключи.забрать) and not КАТАЛОГ_ТАМ:
        print("каталог обмена на той машине не задан (GIS_KB_EXCHANGE): место ещё не "
              "согласовано с владельцем базы знаний — файлы собраны только здесь",
              file=sys.stderr)
        if ключи.забрать:
            return 1

    with db.connect("gis_agent") as conn:
        if ключи.забрать and КАТАЛОГ_ТАМ:
            входящие = ЗДЕСЬ / "внутрь" / f"{datetime.now():%Y%m%d-%H%M}"
            входящие.mkdir(parents=True, exist_ok=True)
            with ingest.run(conn, script=СКРИПТ, note="ответ базы знаний") as run_id:
                scp(f"{МАШИНА}:{КАТАЛОГ_ТАМ}/ответ/.", str(входящие))
                файлы = [п for п in входящие.rglob("*") if п.is_file()]
                for п in файлы:
                    ingest.add_artifact(conn, run_id, п, "обмен с базой знаний: внутрь")
                ingest.add_metric(conn, run_id, "файлов получено", len(файлы))
                conn.commit()
            print(f"забрано файлов: {len(файлы)} → {входящие}")
            return 0

        каталог = ЗДЕСЬ / "наружу" / f"{datetime.now():%Y%m%d-%H%M}"
        каталог.mkdir(parents=True, exist_ok=True)
        with ingest.run(conn, script=СКРИПТ, note="вердикты и темы наружу") as run_id:
            данные = вердикты(conn)
            путь_в = каталог / "вердикты.json"
            путь_в.write_text(json.dumps(данные, ensure_ascii=False, indent=2, default=str),
                              encoding="utf-8")
            путь_т = каталог / "темы-gis.yaml"
            путь_т.write_text(темы(conn), encoding="utf-8")
            for п in (путь_в, путь_т):
                ingest.add_artifact(conn, run_id, п, "обмен с базой знаний: наружу")
            ingest.add_metric(conn, run_id, "решений по цитатам", len(данные["цитаты"]))
            ingest.add_metric(conn, run_id, "решений по якорям", len(данные["якоря"]))
            if ключи.отправить and КАТАЛОГ_ТАМ:
                scp(str(каталог), f"{МАШИНА}:{КАТАЛОГ_ТАМ}/")
            conn.commit()

    print(f"собрано: {каталог}")
    print(f"  решений по цитатам {len(данные['цитаты'])}, по якорям {len(данные['якоря'])}")
    print(f"  порог близости: {данные['замер_порога']['вывод']}")
    if ключи.отправить and КАТАЛОГ_ТАМ:
        print(f"  отправлено на {МАШИНА}:{КАТАЛОГ_ТАМ}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
