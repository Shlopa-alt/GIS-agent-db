"""Туннель до машины базы знаний и проверка связи.

База знаний стоит на другом компьютере в той же беспроводной сети и слушает
только себя (`127.0.0.1:8000`). Туннель подставляет её порт на наш, поэтому в
коде моста нет ни адресов, ни имён машин: он ходит на `localhost:8000` и там, и
на машине базы знаний.

Почему отдельный скрипт, а не строка в руководстве. Проверять связь надо до
прогона и теми же глазами, какими её видит мост: порт может быть занят старым
туннелем, база знаний — не поднята, правки на её стороне — не применены. Все
три случая выглядят как «не работает», а лечатся по-разному, и скрипт их
различает.

Запуск:
    python scripts/kb_tunnel.py                    поднять туннель и держать
    python scripts/kb_tunnel.py --проверить        только проверить связь
    python scripts/kb_tunnel.py --с-моделью        заодно пробросить сервер моделей
    python scripts/kb_tunnel.py --машина kb --пользователь grisha

Откуда берутся машина и пользователь: переменные `GIS_KB_HOST` и `GIS_KB_USER`,
иначе ключи запуска. Адрес, по которому ходит мост, — `GIS_KB_URL`.
"""

from __future__ import annotations

import argparse
import os
import socket
import subprocess
import sys
import time
from pathlib import Path
from urllib.parse import urlparse

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from gisdb import kb_client  # noqa: E402

#: Порт сервера моделей на машине базы знаний (vLLM в контейнере, протокол общий).
ПОРТ_МОДЕЛИ = 8100


def порт_занят(порт: int, узел: str = "127.0.0.1") -> bool:
    """Слушает ли кто-нибудь этот порт у нас. Занят — туннель, скорее всего, уже есть."""
    with socket.socket() as гнездо:
        гнездо.settimeout(1)
        return гнездо.connect_ex((узел, порт)) == 0


def проверить() -> int:
    """Что отвечает база знаний. Возвращает код выхода: 0 — связь есть."""
    знания = kb_client.БазаЗнаний()
    try:
        состояние = знания.состояние()
    except kb_client.НетСвязи as сбой:
        print(f"связи нет: {сбой}", file=sys.stderr)
        return 1
    print(
        f"база знаний отвечает: статей {состояние['статей']}, "
        f"фрагментов {состояние['фрагментов']}"
    )
    if состояние["полное"]:
        print(f"версия кода {состояние['версия']}, модель векторов {состояние['модель']}")
        if состояние["фактов"] is not None:
            print(f"фактов в графе: {состояние['фактов']}")
    for пометка in знания.пометки:
        print(f"неполно: {пометка}")
    return 0


def поднять(машина: str, пользователь: str, порт: int, с_моделью: bool) -> int:
    """Запустить туннель и держать его, пока не остановят."""
    команда = ["ssh", "-N", "-L", f"{порт}:127.0.0.1:{порт}"]
    if с_моделью:
        команда += ["-L", f"{ПОРТ_МОДЕЛИ}:127.0.0.1:{ПОРТ_МОДЕЛИ}"]
    команда.append(f"{пользователь}@{машина}" if пользователь else машина)
    print("запускаю:", " ".join(команда))
    try:
        процесс = subprocess.Popen(команда)
    except FileNotFoundError:
        print(
            "ssh не найден. Поставьте клиент: «Add-WindowsCapability -Online "
            "-Name OpenSSH.Client~~~~0.0.1.0»",
            file=sys.stderr,
        )
        return 1

    # Ждём, пока порт начнёт отвечать: вход по ключу занимает доли секунды, но
    # по беспроводной сети бывает и несколько.
    for _ in range(20):
        if порт_занят(порт):
            break
        if процесс.poll() is not None:
            print("туннель закрылся сразу — смотрите сообщение ssh выше", file=sys.stderr)
            return процесс.returncode or 1
        time.sleep(0.5)
    else:
        процесс.terminate()
        print(f"порт {порт} так и не ответил", file=sys.stderr)
        return 1

    код = проверить()
    print("туннель держится; остановить — Ctrl+C")
    try:
        процесс.wait()
    except KeyboardInterrupt:
        процесс.terminate()
        print("\nтуннель закрыт")
    return код


def main(аргументы: list[str] | None = None) -> int:
    разбор = argparse.ArgumentParser(description="Туннель до машины базы знаний")
    # «kb» — запись в ~/.ssh/config: имя компьютера, пользователь и ключ там,
    # потому что адрес в общей сети выдаётся по запросу и меняется.
    разбор.add_argument("--машина", default=os.environ.get("GIS_KB_HOST", "kb"))
    разбор.add_argument("--пользователь", default=os.environ.get("GIS_KB_USER", ""))
    разбор.add_argument("--проверить", action="store_true", help="не поднимать, только проверить")
    разбор.add_argument("--с-моделью", action="store_true",
                        help="пробросить и сервер моделей той машины")
    ключи = разбор.parse_args(аргументы)

    порт = urlparse(kb_client.АДРЕС).port or 8000

    if ключи.проверить:
        return проверить()

    if порт_занят(порт):
        print(f"порт {порт} уже отвечает — туннель поднят в другом окне, проверяю связь")
        return проверить()

    if not ключи.машина:
        print(
            "не указана машина базы знаний: ключ --машина или переменная GIS_KB_HOST",
            file=sys.stderr,
        )
        return 2
    return поднять(ключи.машина, ключи.пользователь, порт, ключи.с_моделью)


if __name__ == "__main__":
    raise SystemExit(main())
