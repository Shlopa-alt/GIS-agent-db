"""Выгрузка базы наружу: только подтверждённое и только разрешённое к передаче.

Зачем. Всё, что база знает, пока доступно лишь из неё самой: чтобы показать
паспорта соисполнителю или приложить их к отчёту, приходилось писать запрос
руками. Это не только неудобно — это опасно: 34 слоя из 40 распространять
нельзя (32 — материалы организации, остальные по условиям поставщиков), и
решение «а это точно можно отдать?» каждый раз принималось на глаз.

Что выгружается. Читаются представления схемы `api` (миграция 017), а не
таблицы: наружу идёт только подтверждённое человеком, и состав выгрузки не
зависит от того, что мы переставили внутри базы на этой неделе.

    паспорта-признаков.csv     смысл, покрытие, переносимость, важность
    слои-источники.csv         поставщик, метод, лицензия, права передачи
    понятия.csv                предметная модель
    связи-признак-понятие.csv  чем признак обоснован
    цитаты.csv                 литература под понятиями
    территории.csv
    права-распространения.csv  по каждому признаку: можно ли отдавать значения
    состав.csv                 числа для сверки
    ПРОЧТИ.txt                 что внутри, чьи лицензии, что исключено

Про значения признаков. Их 11,7 млн, и они несут в себе содержимое
слоёв-источников, пусть и свёрнутое в ячейку. Поэтому по умолчанию они не
выгружаются вовсе, а с ключом `--значения` выгружаются только у признаков,
все источники которых разрешено распространять. Признаки без слоёв-источников
(посчитанные внутри проекта) в выгрузку значений не попадают: решение по ним
принимает человек, а не умолчание скрипта.

Выгрузка записывается в журнал прогонов артефактами с отпечатками: видно, что
именно и когда ушло наружу.

    python scripts/db_export.py --проверить        что попадёт в выгрузку
    python scripts/db_export.py
    python scripts/db_export.py --значения
    python scripts/db_export.py --куда C:/обмен/выгрузка-для-отчёта
"""

from __future__ import annotations

import argparse
import csv
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from gisdb import db  # noqa: E402
from gisdb import db_ingest as ingest  # noqa: E402

СКРИПТ = "scripts/db_export.py"

# Представление схемы `api` → имя файла. Порядок — порядок чтения человеком:
# сперва признаки, потом откуда они, потом чем обоснованы.
СОСТАВ: tuple[tuple[str, str], ...] = (
    ("feature", "паспорта-признаков.csv"),
    ("layer", "слои-источники.csv"),
    ("concept", "понятия.csv"),
    ("feature_concept", "связи-признак-понятие.csv"),
    ("citation", "цитаты.csv"),
    ("territory", "территории.csv"),
    ("redistribution", "права-распространения.csv"),
    ("summary", "состав.csv"),
)

ЗНАЧЕНИЯ = """
SELECT f.code AS признак, c.row AS ряд, c.col AS столбец, v.value AS значение
  FROM data.feature_value v
  JOIN data.feature f ON f.id = v.feature_id
  JOIN data.cell c ON c.id = v.cell_id
  JOIN api.redistribution р ON р.признак = f.code
 WHERE р.можно_распространять
 ORDER BY f.code, c.row, c.col
"""

ПРОЧТИ = """Выгрузка базы «{база}» от {дата}

Что внутри
{состав}

Откуда это
База собрана агентами и проверена человеком: каждый паспорт, каждое понятие и
каждая связь имеют подпись проверяющего и время подтверждения — они в столбцах
«подтвердил» и «подтверждено». Черновики, которые ещё не прошли проверку, в
выгрузку не входят.

Права на передачу
{лицензии}

Значения признаков
{значения}

Признак нельзя передавать, если хотя бы один слой, из которого он посчитан,
распространять запрещено: значения несут в себе содержимое слоя, пусть и
свёрнутое в ячейку. По каждому признаку это сказано в «права-распространения.csv»
вместе с причиной.

Сверка
Числа в «состав.csv» сняты из базы в момент выгрузки. Если файлы правили
руками, числа перестанут сходиться — так это и задумано.

Выгрузка записана в журнал прогонов базы: прогон #{прогон}.
"""


def строки(conn, вид: str) -> tuple[list[str], list[tuple]]:
    курсор = conn.execute(f"SELECT * FROM api.{вид}")
    заголовок = [о.name for о in курсор.description]
    return заголовок, курсор.fetchall()


def по_русски(значение):
    """Значение для файла, который читает человек, а не программа.

    `True` и `False` в столбце «можно_распространять» — это ответ на русский
    вопрос латинскими словами; человек, открывший файл в Excel, прочтёт его
    как код. Пустая клетка остаётся пустой: «нет данных» и «нет» — разное.
    """
    if значение is None:
        return ""
    if isinstance(значение, bool):
        return "да" if значение else "нет"
    return значение


def записать_csv(путь: Path, заголовок: list[str], ряды) -> int:
    # Разделитель — точка с запятой: Excel с русскими настройками иначе
    # складывает всю строку в одну клетку. utf-8-sig — чтобы он же не принял
    # кириллицу за кракозябры.
    сколько = 0
    with путь.open("w", encoding="utf-8-sig", newline="") as ф:
        писарь = csv.writer(ф, delimiter=";")
        писарь.writerow(заголовок)
        for ряд in ряды:
            писарь.writerow([по_русски(з) for з in ряд])
            сколько += 1
    return сколько


def числом(сколько: int) -> str:
    """6853897 → «6 853 897»: семизначное число иначе не прочитать глазами."""
    return f"{сколько:,}".replace(",", " ")


def слоёв(сколько: int) -> str:
    """«1 слой», «2 слоя», «32 слоя»: падеж попадает в файл для человека."""
    последняя, две = сколько % 10, сколько % 100
    if последняя == 1 and две != 11:
        return f"{сколько} слой"
    if последняя in (2, 3, 4) and две not in (12, 13, 14):
        return f"{сколько} слоя"
    return f"{сколько} слоёв"


def лицензии(conn) -> str:
    ряды = conn.execute(
        """SELECT лицензия, лицензия_название, лицензия_адрес,
                  можно_распространять, count(*)
             FROM api.layer GROUP BY 1, 2, 3, 4 ORDER BY 4 DESC, 5 DESC"""
    ).fetchall()
    куски = []
    for код, название, адрес, можно, сколько in ряды:
        знак = "можно передавать" if можно else "ПЕРЕДАВАТЬ НЕЛЬЗЯ"
        куски.append(f"  {код or 'без лицензии'} — {слоёв(сколько)}, {знак}"
                     + (f"\n    {название}" if название else "")
                     + (f"\n    {адрес}" if адрес else ""))
    return "\n".join(куски) or "  слоёв с подтверждённым паспортом нет"


def main(аргументы: list[str] | None = None) -> int:
    разбор = argparse.ArgumentParser(description="Выгрузка базы наружу")
    разбор.add_argument("--куда", type=Path, help="каталог выгрузки")
    разбор.add_argument("--значения", action="store_true",
                        help="добавить значения признаков, разрешённых к передаче")
    разбор.add_argument("--проверить", action="store_true",
                        help="показать состав выгрузки, ничего не записывая")
    ключи = разбор.parse_args(аргументы)

    каталог = ключи.куда or (db.ROOT / "выгрузка" / f"{db.DBNAME}_{date.today():%Y%m%d}")

    with db.connect("gis_read") as conn:
        for что, сколько in conn.execute("SELECT что, сколько FROM api.summary").fetchall():
            print(f"  {что:40} {сколько}")
        можно_значений = conn.execute(
            "SELECT count(*) FROM api.redistribution WHERE можно_распространять"
        ).fetchone()[0]
        нельзя = conn.execute(
            "SELECT count(*) FROM api.redistribution WHERE NOT можно_распространять"
        ).fetchone()[0]
        сами = conn.execute(
            "SELECT count(*) FROM api.redistribution WHERE можно_распространять IS NULL"
        ).fetchone()[0]
        print(f"\nзначения признаков: можно передавать {можно_значений}, "
              f"нельзя {нельзя}, без слоёв-источников {сами}")
        print(f"каталог выгрузки: {каталог}")
        if ключи.проверить:
            print("\nбудут записаны:")
            for _, имя in СОСТАВ:
                print(f"  {имя}")
            print("  ПРОЧТИ.txt")
            if ключи.значения:
                сколько = conn.execute(
                    """SELECT count(*) FROM data.feature_value v
                         JOIN data.feature f ON f.id = v.feature_id
                         JOIN api.redistribution р ON р.признак = f.code
                        WHERE р.можно_распространять"""
                ).fetchone()[0]
                # 6,9 млн строк — это четверть гигабайта, и узнавать об этом
                # из заполненного диска неприятно.
                print(f"  значения-признаков.csv — {сколько} строк, "
                      f"примерно {сколько * 38 / 2**20:.0f} МБ")
            print("\nпроверка: ничего не записано")
            return 0

        каталог.mkdir(parents=True, exist_ok=True)
        with db.connect("gis_agent") as журнал:
            with ingest.run(журнал, script=СКРИПТ,
                            note=f"выгрузка в {db.store_ref(каталог)}") as run_id:
                сведения = []
                for вид, имя in СОСТАВ:
                    заголовок, ряды = строки(conn, вид)
                    путь = каталог / имя
                    записать_csv(путь, заголовок, ряды)
                    сведения.append((имя, len(ряды)))
                    ingest.add_artifact(журнал, run_id, путь, "выгрузка", f"api.{вид}")
                    print(f"  {имя:32} {len(ряды):8} строк")

                если_значения = "не выгружены: ключ --значения не задан"
                if ключи.значения:
                    курсор = conn.execute(ЗНАЧЕНИЯ)
                    заголовок = [о.name for о in курсор.description]
                    путь = каталог / "значения-признаков.csv"
                    сколько = записать_csv(путь, заголовок, курсор.fetchall())
                    сведения.append(("значения-признаков.csv", сколько))
                    ingest.add_artifact(журнал, run_id, путь, "выгрузка",
                                        "значения признаков, разрешённых к передаче")
                    print(f"  {'значения-признаков.csv':32} {сколько:8} строк")
                    если_значения = (
                        f"Выгружено значений: {числом(сколько)} — по "
                        f"{можно_значений} признакам, у которых все "
                        "слои-источники разрешено распространять.\n"
                        f"Исключены признаки с запрещёнными источниками: {нельзя}.\n"
                        "Исключены признаки без слоя-источника, посчитанные "
                        f"внутри проекта: {сами} (решение по ним — за человеком)."
                    )

                прочти = каталог / "ПРОЧТИ.txt"
                прочти.write_text(
                    ПРОЧТИ.format(
                        база=db.DBNAME, дата=f"{date.today():%d.%m.%Y}",
                        состав="\n".join(f"  {и:32} {числом(с):>11} строк"
                                         for и, с in сведения),
                        лицензии=лицензии(conn), значения=если_значения, прогон=run_id,
                    ),
                    encoding="utf-8",
                )
                ingest.add_artifact(журнал, run_id, прочти, "описание",
                                    "состав выгрузки и права на передачу")
                ingest.add_metric(журнал, run_id, "файлов выгружено", len(сведения) + 1)
                ingest.add_metric(журнал, run_id, "строк выгружено",
                                  sum(с for _, с in сведения))
                журнал.commit()

    print(f"\nвыгрузка готова: {каталог}")
    print(f"прочтите {прочти.name} — там лицензии и что исключено; прогон #{run_id}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
