"""Подбор якорей понятий: чему в графе фактов базы знаний отвечает понятие.

Без якоря мост (`scripts/db_kb_evidence.py`) не заходит в граф фактов вовсе и
берёт всё смысловым поиском по фрагментам, где за цитатой стоит только
близость векторов. За фактом графа стоит цитата, проверенная кодом базы
знаний: она есть в статье, и в ней видны оба конца связи. Якорь — то, что
включает этот путь.

Как подбирается. У каждого понятия — список основ слов, по-русски и
по-английски, выписанный из его определения (`ОСНОВЫ`). Сущности графа, в имени
или написаниях которых встречается основа с начала слова, ранжируются по числу
статей, потом фактов; сущность из одной статьи по умолчанию отбрасывается — её
нечем подтвердить (то же правило у самой базы знаний, `graph/gaps.py`).
Лучшие ложатся в `bridge.concept_anchor` черновиками; подтверждает человек в
панели. Модель здесь не участвует: отнесение к понятиям она делает плохо
(замер 26.10.2026 — 11 из 17 связей хуже подтверждённых), а подбор словами
виден и проверяем.

Нет ни одной подходящей сущности — пишется черновик «в графе нет» с запасным
запросом по фрагментам. Это содержательный ответ, а не сбой: условие
наблюдения статьи по геологии фактами не описывают.

Запуск:
    python scripts/db_kb_anchors.py                  все понятия
    python scripts/db_kb_anchors.py --сухой          показать, ничего не записывая
    python scripts/db_kb_anchors.py --понятие магматизм
    python scripts/db_kb_anchors.py --на-понятие 8 --мин-статей 3

Перед запуском нужен туннель: `python scripts/kb_tunnel.py`.
"""

