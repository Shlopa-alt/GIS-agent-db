#: Имена нашей территории в графе — не якоря понятий, а мерило того, сколько в
#: корпусе вообще сказано про нашу площадь. Отсюда темы на добычу статей.
ТЕРРИТОРИЯ = ("Анабар", "Anabar", "Билля", "Billyakh", "Хаптасын", "Котуйкан", "Kotuykan")

ПОНЯТИЯ = """
SELECT code, kind, definition
  FROM kb.concept
 WHERE status <> 'отклонён' AND kind <> 'критерий'{ещё}
 ORDER BY kind, code
"""


# ------------------------------------------------------------------- подбор
def _шаблон(основа: str) -> re.Pattern:
    """Основа с начала слова: «дайк» не должна ловить «прайдайк»."""
    return re.compile(r"(?<![\w-])" + re.escape(основа.lower()))


def совпадение(сущность: dict, основы: tuple[str, ...]) -> str | None:
    """По какой основе сущность подошла; не подошла — None."""
    тексты = [сущность["имя"], *сущность.get("написания", [])]
    for основа in основы:
        шаблон = _шаблон(основа)
        if any(шаблон.search(т.lower()) for т in тексты):
            return основа
    return None


def подобрать(сущности: list[dict], основы: tuple[str, ...], сколько: int,
              мин_статей: int) -> list[dict]:
    """Лучшие сущности под понятие: больше статей, потом больше фактов.

    Статьи важнее фактов: двадцать фактов из одной статьи — это одна статья,
    а якорь нужен на то, о чём пишут многие.
    """
    найдено = []
    for с in сущности:
        if с["статей"] < мин_статей:
            continue
        основа = совпадение(с, основы)
        if основа:
            найдено.append({**с, "основа": основа})
    найдено.sort(key=lambda с: (-с["статей"], -с["фактов"], с["имя"]))
    return найдено[:сколько]


def территория(сущности: list[dict]) -> list[dict]:
    """Сущности, названные именами нашей площади, — самые богатые первыми."""
    out = [с for с in сущности if совпадение(с, ТЕРРИТОРИЯ)]
    return sorted(out, key=lambda с: (-с["статей"], -с["фактов"], с["имя"]))


def запасной_запрос(код: str, определение: str | None) -> str:
    """Запрос по фрагментам, когда графу понятию сопоставить нечего."""
    первое = re.split(r"(?<=[.;])\s+", " ".join((определение or "").split()))[0]
    return f"{код}. {первое}"[:300]


def пометка(с: dict, снимок: str) -> str:
    return (f"подобрано по основе «{с['основа']}»: фактов {с['фактов']}, "
            f"статей {с['статей']}, вид «{с['вид'] or 'не указан'}»; граф на {снимок}")


# ------------------------------------------------------------------- запись
def записать_якорь(conn, код: str, с: dict, связи: tuple[str, ...], снимок: str) -> int:
    """Черновик якоря; известный обновляется, пока он черновик."""
    return conn.execute(
        """INSERT INTO bridge.concept_anchor (concept_code, kb_name, relations, note)
           VALUES (%s, %s, %s, %s)
           ON CONFLICT (concept_code, kb_name) DO UPDATE SET
               note = EXCLUDED.note
           WHERE bridge.concept_anchor.status = 'черновик'""",
        (код, с["имя"], list(связи), пометка(с, снимок)),
    ).rowcount


def записать_отсутствие(conn, код: str, запрос: str, снимок: str) -> int:
    """Черновик «в графе нет», если такого ещё нет ни в каком статусе.

    Уникальность по имени здесь не помогает — имени нет, — поэтому проверка
    явная: повторный запуск не должен плодить одинаковые «нет».
    """
    есть = conn.execute(
        "SELECT 1 FROM bridge.concept_anchor WHERE concept_code = %s AND absent",
        (код,),
    ).fetchone()
    if есть:
        return 0
    return conn.execute(
        """INSERT INTO bridge.concept_anchor (concept_code, absent, query, note)
           VALUES (%s, true, %s, %s)""",
        (код, запрос, f"в графе на {снимок} подходящих сущностей не нашлось; "
                     "цитаты — поиском по фрагментам"),
    ).rowcount


# ---------------------------------------------------------------------- ход
def main(аргументы: list[str] | None = None) -> int:
    разбор = argparse.ArgumentParser(description="Подбор якорей понятий в графе базы знаний")
    разбор.add_argument("--сухой", action="store_true", help="показать, ничего не записывая")
    разбор.add_argument("--понятие", default=None, help="только одно понятие")
    разбор.add_argument("--на-понятие", type=int, default=5, help="сколько якорей предлагать")
    разбор.add_argument("--мин-статей", type=int, default=2,
                        help="сущность из меньшего числа статей не предлагать")
    разбор.add_argument("--адрес", default=kb_client.АДРЕС)
    ключи = разбор.parse_args(аргументы)

    знания = kb_client.БазаЗнаний(ключи.адрес)
    try:
        состояние = знания.состояние()
        сущности = знания.граф()
    except kb_client.НетСвязи as сбой:
        print(сбой, file=sys.stderr)
        return 1
    снимок = str(состояние.get("проверено") or состояние.get("версия") or "неизвестную дату")
    print(f"база знаний {ключи.адрес}: статей {состояние['статей']}, "
          f"фактов {состояние['фактов']}, сущностей в графе {len(сущности)}")

    with db.connect("gis_agent") as conn:
        понятия = conn.execute(
            ПОНЯТИЯ.format(ещё=" AND code = %s" if ключи.понятие else ""),
            (ключи.понятие,) if ключи.понятие else (),
        ).fetchall()
        if not понятия:
            print("понятий для работы нет", file=sys.stderr)
            return 1

        предложения: dict[str, list[dict]] = {}
        for код, род, _ in понятия:
            основы = ОСНОВЫ.get(код)
            if not основы:
                print(f"  {код}: основ слов нет в ОСНОВЫ — пропущено")
                continue
            предложения[код] = подобрать(сущности, основы, ключи.на_понятие, ключи.мин_статей)
            найдено = предложения[код]
            print(f"  {код}: {len(найдено)}" + (
                " — " + "; ".join(f"{с['имя']} ({с['статей']} ст., {с['фактов']} ф.)"
                                  for с in найдено) if найдено else " — в графе нет"))

        своя = территория(сущности)
        print(f"\nимён нашей территории в графе: {len(своя)}"
              + (" — " + "; ".join(f"{с['имя']} ({с['статей']} ст.)" for с in своя[:10])
                 if своя else ""))

        if ключи.сухой:
            print("\nсухой прогон: ничего не записано")
            return 0

        роды = {код: род for код, род, _ in понятия}
        определения = {код: о for код, _, о in понятия}
        with ingest.run(conn, script=СКРИПТ,
                        note=f"якоря по {len(предложения)} понятиям") as run_id:
            прошлый = kb_snapshot.записать(conn, состояние, СКРИПТ, run_id,
                                           сущностей=len(сущности))
            print("  " + kb_snapshot.сравнение(прошлый, состояние))
            якорей = отсутствий = 0
            for код, найдено in предложения.items():
                связи = СВЯЗИ_ПО_РОДУ.get(роды[код], ())
                for с in найдено:
                    якорей += записать_якорь(conn, код, с, связи, снимок)
                if not найдено:
                    отсутствий += записать_отсутствие(
                        conn, код, запасной_запрос(код, определения[код]), снимок)
            ingest.add_metric(conn, run_id, "сущностей в графе", len(сущности))
            ingest.add_metric(conn, run_id, "якорей предложено", якорей)
            ingest.add_metric(conn, run_id, "понятий без якоря", отсутствий)
            ingest.add_metric(conn, run_id, "имён территории в графе", len(своя))
            conn.commit()
            print(f"\nзаписано: якорей {якорей}, «в графе нет» {отсутствий}; прогон #{run_id}")
            print("дальше — панель подтверждений, очередь «Якоря понятий»")
    for п in знания.пометки:
        print(f"  неполно: {п}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
