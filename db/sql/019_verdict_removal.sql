-- 019: снятие вердикта — тоже вердикт.
-- Запускается от gisadmin после 018_concept_level.sql (через db/migrate.py).
--
-- Что нашлось. Правило базы запрещало агенту **ставить** статус «подтверждён» и
-- «отклонён», но не запрещало **снимать** уже поставленный. Проверено на живой
-- базе ролью gis_agent:
--
--     паспорт 213: подтверждён
--     агент снял подтверждение: стало «черновик», подпись None
--
-- Подпись при этом стирается — так устроен тот же триггер: статус не «подтверждён»,
-- значит `confirmed_by` и `confirmed_at` обнуляются. В `meta.review` не ложится
-- ничего: журнал ведёт панель, а агент ходит мимо неё. То есть решение человека
-- можно было стереть без следа, и это в базе, вся ценность которой — в том, что за
-- каждым утверждением стоит подпись.
--
-- Почему дыра появилась. Запрет был написан как «агент не может поставить
-- вердикт» и смотрел только на новое значение. Снятие вердикта по этой проверке
-- выглядит переходом в «черновик» — то есть в безобидное состояние. Но вердикт
-- человека — это не состояние строки, а событие; отменить событие может только
-- тот, кто вправе его совершить.
--
-- Что меняется. Любой переход строки ИЗ «подтверждён» или «отклонён» теперь
-- доступен только члену `gis_confirmer`. Агент по-прежнему пишет черновики и
-- по-прежнему не может тронуть подтверждённую строку — ни один её столбец.
--
-- Чего это не ломает. Возврат объекта на доработку остаётся: его делает человек
-- в панели кнопкой «Вернуть на доработку», и это ложится в `meta.review`
-- решением «черновик» с причиной. Именно этот путь нужен, чтобы переписать
-- 47 паспортов, сделанных не тем исполнителем: человек возвращает их на
-- доработку, локальная модель описывает заново, человек подтверждает.

CREATE OR REPLACE FUNCTION meta.guard_confirmation() RETURNS trigger
LANGUAGE plpgsql AS $fn$
DECLARE
    human boolean := pg_has_role(current_user, 'gis_confirmer', 'MEMBER');
BEGIN
    IF NEW.status IN ('подтверждён', 'отклонён') AND NOT human THEN
        RAISE EXCEPTION
            'Статус «%» в %.% ставит только человек; роль % на это не уполномочена',
            NEW.status, TG_TABLE_SCHEMA, TG_TABLE_NAME, current_user;
    END IF;

    -- Снятие вердикта — тоже вердикт. Без этой проверки агент возвращал
    -- подтверждённую строку в «черновик» и стирал подпись человека.
    IF TG_OP = 'UPDATE'
       AND OLD.status IN ('подтверждён', 'отклонён')
       AND NEW.status IS DISTINCT FROM OLD.status
       AND NOT human THEN
        RAISE EXCEPTION
            'Решение человека по %.% снимает только человек: строка в статусе «%», '
            'роль % не уполномочена вернуть её в «%»',
            TG_TABLE_SCHEMA, TG_TABLE_NAME, OLD.status, current_user, NEW.status;
    END IF;

    IF NEW.status = 'подтверждён' THEN
        NEW.confirmed_by := coalesce(NEW.confirmed_by, current_user);
        NEW.confirmed_at := coalesce(NEW.confirmed_at, now());
    ELSE
        NEW.confirmed_by := NULL;
        NEW.confirmed_at := NULL;
    END IF;

    RETURN NEW;
END
$fn$;

COMMENT ON FUNCTION meta.guard_confirmation() IS
    'Агент пишет черновики; ставит и снимает вердикт только член gis_confirmer';
