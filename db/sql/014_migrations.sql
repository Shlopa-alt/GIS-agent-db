-- 014: учёт применённых миграций.
-- Применяется первой из всех — её накатывает сам db/migrate.py, если таблицы
-- ещё нет. Повторный запуск безопасен.
--
-- Зачем. До этой таблицы база не знала, какие из тринадцати файлов схемы уже
-- прошли. Последствие было настоящим: с 30.09 по 22.10 база жила без миграций
-- 011 и 012, и узнать это можно было только выборкой по списку таблиц.
-- Установку в таком виде нельзя ни воспроизвести, ни обновить — ни у себя, ни
-- тем более у того, кому систему передадут.
--
-- Контрольная сумма хранится не ради порядка: если файл схемы правят задним
-- числом, базы, накатанные до и после правки, различаются при одинаковом
-- списке применённого. Сверка суммы это ловит.

CREATE TABLE IF NOT EXISTS meta.migration (
    filename   text PRIMARY KEY,                       -- '003_confirmation_rules.sql'
    checksum   text NOT NULL,                          -- sha256 файла на момент применения
    applied_at timestamptz NOT NULL DEFAULT now(),
    applied_by text NOT NULL DEFAULT current_user,
    seconds    double precision,                       -- сколько заняло применение
    note       text                                    -- 'отмечена применённой задним числом'
);

COMMENT ON TABLE meta.migration IS
    'Какие файлы схемы применены к этой базе; питает db/migrate.py';
COMMENT ON COLUMN meta.migration.note IS
    'Пометка о том, что миграция зарегистрирована без исполнения — для баз, накатанных вручную';

GRANT SELECT ON meta.migration TO gis_read, gis_agent, gis_human;
