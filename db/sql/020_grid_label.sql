-- 020: исправление имени сетки у признаков сборки dataset_v6.
-- Запускается от gisadmin после 019_verdict_removal.sql (через db/migrate.py).
--
-- Что нашлось. Осмотр агента-сборщика (узел 3) доложил: 105 признаков ссылаются
-- на сетку `лист-R-49-I-II-500м`, которой в `data.grid` нет. Выглядит как данные
-- другого листа, но это не они. Проверка по базе:
--
--   * значения этих признаков — 2 235 410 штук — лежат на ячейках сетки
--     `лист-R-48-XI-XII-500м`, территория «Основной лист R-48-XI,XII»;
--   * в сетке основного листа 22 946 ячеек — ровно столько же названо в
--     материалах проекта для листа R-48-XI,XII;
--   * файл-источник у всех 105 — `проект:/data/processed/dataset_v6.parquet`,
--     то есть основной рабочий набор листа;
--   * записал их прогон #1 от 13.09.2026, скрипт `experiments/db_load_datasets.py`
--     — тогдашнее место загрузчика, до выделения базы в свой репозиторий.
--
-- То есть данные основного листа подписаны именем его северо-восточного соседа.
-- R-49-I,II — отдельный лист, он примыкает к нашему только углом, и на нём
-- оцифрована золоторудная зона; к сборке dataset_v6 он отношения не имеет.
--
-- Загрузчик уже исправлен: сегодняшний `scripts/db_load_datasets.py` передаёт
-- `лист-R-48-XI-XII-500м`. Исправлен был код, а записанные строки остались —
-- поэтому заводить сетку `лист-R-49-I-II-500м` было бы ошибкой: она закрепила бы
-- неверную подпись и навсегда развела данные основного листа на две территории.
--
-- Чем это стоило. Любой запрос «что собрано по территории» не видел этих
-- признаков: связь идёт через имя сетки, а оно ни на что не указывало. В описи
-- у основного листа стояло «кодов признаков 0» при 2,2 млн значений.
--
-- Правка затрагивает только подпись в `definition`: ни одно значение, ни одна
-- ячейка и ни один паспорт не меняются. Поле «сборка» остаётся прежним, поэтому
-- уникальность версий признака (`feature_one_current`) не задета.

DO $$
DECLARE
    сколько integer;
    чужих   integer;
BEGIN
    -- Страховка: правим только то, чьи значения действительно лежат на сетке
    -- основного листа. Если найдётся признак с этим именем, но с ячейками другой
    -- сетки, — это уже не опечатка, и решать надо не миграцией.
    SELECT count(*) INTO чужих
      FROM data.feature f
     WHERE f.definition->>'сетка' = 'лист-R-49-I-II-500м'
       AND EXISTS (
             SELECT 1 FROM data.feature_value v
               JOIN data.cell c ON c.id = v.cell_id
               JOIN data.grid g ON g.id = c.grid_id
              WHERE v.feature_id = f.id AND g.code <> 'лист-R-48-XI-XII-500м');
    IF чужих > 0 THEN
        RAISE EXCEPTION
            'У % признаков с именем «лист-R-49-I-II-500м» значения лежат не на '
            'сетке основного листа — это не опечатка загрузчика, разберите вручную',
            чужих;
    END IF;

    UPDATE data.feature f
       SET definition = jsonb_set(f.definition, '{сетка}', '"лист-R-48-XI-XII-500м"')
     WHERE f.definition->>'сетка' = 'лист-R-49-I-II-500м';
    GET DIAGNOSTICS сколько = ROW_COUNT;
    RAISE NOTICE 'имя сетки исправлено у % признаков', сколько;
END
$$;

-- После правки ни один признак не должен ссылаться на незаведённую сетку: это
-- то самое свойство, отсутствие которого скрывало ошибку четыре недели.
DO $$
DECLARE
    ничьих integer;
BEGIN
    SELECT count(*) INTO ничьих
      FROM data.feature f
     WHERE f.definition ? 'сетка'
       AND NOT EXISTS (SELECT 1 FROM data.grid g WHERE g.code = f.definition->>'сетка');
    IF ничьих > 0 THEN
        RAISE EXCEPTION
            'Признаков, ссылающихся на незаведённую сетку, осталось %: '
            'заведите сетку в data.grid или исправьте код в сборке', ничьих;
    END IF;
END
$$;
