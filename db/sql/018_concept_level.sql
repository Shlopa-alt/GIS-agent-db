-- 018: уровень «критерий» в предметной модели и дерево понятий.
-- Запускается от gisadmin после 017_api.sql (через db/migrate.py).
--
-- Зачем. Предметная модель проекта — цепочка «этап процесса → рудоконтролирующий
-- фактор → критерий → наблюдаемый признак → числовой канал». В базе из неё есть
-- только два конца: 8 понятий уровня «фактор» и 240 признаков. Середины нет, и
-- это видно по числам: из 218 подтверждённых связей 110 висят на одном понятии
-- «обнажённость и растительный покров», 35 на «структурном контроле», а на
-- «палеодолинах» — три.
--
-- Что это значит на деле. Карта на знаниях должна отвечать, почему именно эта
-- клетка перспективна. Ответ «потому что обнажённость и растительный покров»
-- не объясняет ничего: под ним 110 разных признаков, и к оруднению он вообще
-- не относится — это условие наблюдения. Нужен уровень, на котором один
-- элемент отвечает за одну проверяемую вещь: не «гидротермальные изменения»
-- вообще, а «вынос магнетита в зоне переработки» или «серицит-мусковитовая
-- кайма». Это и есть критерий.
--
-- Что делает эта миграция. Только устройство: место для уровней, правило их
-- порядка, два вида наружу и три этапа генетической модели. Сами критерии
-- заводятся отдельно: это суждение, его пишет агент черновиком и подтверждает
-- человек, а не строка в DDL.
--
-- Чего она намеренно не делает. Не трогает ни одного подтверждённого понятия.
-- Поставить 8 факторам их этап — утверждение о предметной модели, а не
-- техническая правка: его выносит человек в панели. Правило базы это и так не
-- даст обойти (`meta.guard_confirmation` отказывает на любой правке
-- подтверждённой строки), и обходить его миграцией было бы хуже всего:
-- подпись осталась бы прежней, а содержание изменилось.

-- ------------------------------------------------------------ уровень выше
ALTER TABLE kb.concept ADD COLUMN IF NOT EXISTS parent_code text;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'concept_parent_fkey') THEN
        ALTER TABLE kb.concept ADD CONSTRAINT concept_parent_fkey
            FOREIGN KEY (parent_code) REFERENCES kb.concept(code);
    END IF;
END
$$;

CREATE INDEX IF NOT EXISTS concept_parent_idx ON kb.concept (parent_code);

COMMENT ON COLUMN kb.concept.parent_code IS
    'Понятие уровнем выше: у критерия — фактор, у фактора — этап процесса, у этапа — пусто';

-- ------------------------------------------------------------- четыре вида
-- «Этап процесса» сверху и «критерий» снизу: прежние два вида — середина.
DO $$
BEGIN
    ALTER TABLE kb.concept DROP CONSTRAINT IF EXISTS concept_kind_check;
    ALTER TABLE kb.concept ADD CONSTRAINT concept_kind_check CHECK (kind IN (
        'этап процесса',              -- когда в истории это происходило
        'рудоконтролирующий фактор',  -- отвечает за оруднение
        'условие наблюдения',         -- отвечает за то, что видно съёмке
        'критерий'));                 -- одна проверяемая вещь под фактором
END
$$;

COMMENT ON COLUMN kb.concept.kind IS
    'Уровень предметной модели: этап процесса → фактор (или условие наблюдения) → критерий';

-- -------------------------------------------------------- порядок уровней
-- Без этого правила дерево разъедется молча: критерий окажется под критерием,
-- фактор под фактором, и запрос «чем обоснована клетка» начнёт возвращать то
-- мусор, то пустоту — причём не в день ошибки, а через месяц.
CREATE OR REPLACE FUNCTION kb.guard_concept_level() RETURNS trigger
LANGUAGE plpgsql AS $fn$
DECLARE
    вид_выше text;
BEGIN
    IF NEW.parent_code = NEW.code THEN
        RAISE EXCEPTION 'Понятие «%» не может стоять под самим собой', NEW.code;
    END IF;

    IF NEW.parent_code IS NOT NULL THEN
        SELECT kind INTO вид_выше FROM kb.concept WHERE code = NEW.parent_code;
    END IF;

    IF NEW.kind = 'этап процесса' AND NEW.parent_code IS NOT NULL THEN
        RAISE EXCEPTION
            'Этап процесса — верхний уровень: у «%» не может быть понятия выше', NEW.code;
    END IF;

    IF NEW.kind IN ('рудоконтролирующий фактор', 'условие наблюдения')
       AND NEW.parent_code IS NOT NULL AND вид_выше <> 'этап процесса' THEN
        RAISE EXCEPTION
            'Над фактором «%» может стоять только этап процесса, а стоит «%» (%)',
            NEW.code, NEW.parent_code, вид_выше;
    END IF;

    IF NEW.kind = 'критерий' THEN
        IF NEW.parent_code IS NULL THEN
            RAISE EXCEPTION
                'Критерий «%» заведён без фактора: критерий без того, что он '
                'проверяет, ничего не объясняет', NEW.code;
        END IF;
        IF вид_выше NOT IN ('рудоконтролирующий фактор', 'условие наблюдения') THEN
            RAISE EXCEPTION
                'Над критерием «%» должен стоять фактор или условие наблюдения, '
                'а стоит «%» (%)', NEW.code, NEW.parent_code, вид_выше;
        END IF;
    END IF;

    RETURN NEW;
END
$fn$;

COMMENT ON FUNCTION kb.guard_concept_level() IS
    'Порядок уровней предметной модели: этап → фактор → критерий, и никак иначе';

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger
                    WHERE tgname = 'guard_concept_level'
                      AND tgrelid = 'kb.concept'::regclass) THEN
        CREATE TRIGGER guard_concept_level BEFORE INSERT OR UPDATE ON kb.concept
            FOR EACH ROW EXECUTE FUNCTION kb.guard_concept_level();
    END IF;
END
$$;

-- -------------------------------------------------------------- дерево модели
-- Отсюда читается объяснение участка карты: от признака вверх до этапа.
CREATE OR REPLACE VIEW kb.concept_tree AS
    SELECT к.code                                     AS понятие,
           к.kind                                     AS уровень,
           к.status                                   AS состояние,
           CASE к.kind
               WHEN 'этап процесса' THEN к.code
               WHEN 'критерий'      THEN д.code
               ELSE                      в.code
           END                                        AS этап,
           CASE к.kind
               WHEN 'критерий' THEN в.code
               WHEN 'этап процесса' THEN NULL
               ELSE к.code
           END                                        AS фактор,
           CASE WHEN к.kind = 'критерий' THEN к.code END AS критерий,
           (SELECT count(*) FROM bridge.feature_concept b
             WHERE b.concept_code = к.code AND b.status = 'подтверждён') AS признаков,
           к.definition                               AS определение
      FROM kb.concept к
      LEFT JOIN kb.concept в ON в.code = к.parent_code
      LEFT JOIN kb.concept д ON д.code = в.parent_code;

COMMENT ON VIEW kb.concept_tree IS
    'Предметная модель деревом: от признака вверх до этапа процесса';

-- ------------------------------------------------------- чего в модели нет
-- Вид, который говорит, где модель ещё не достроена. Нужен затем же, зачем
-- `meta.feature_term_gap`: пробел должен быть виден запросом, а не всплывать
-- на показе.
CREATE OR REPLACE VIEW kb.concept_gap AS
    SELECT 'фактор без критериев'::text AS чего_нет, c.code AS понятие,
           NULL::text AS признак
      FROM kb.concept c
     WHERE c.kind IN ('рудоконтролирующий фактор', 'условие наблюдения')
       AND c.status <> 'отклонён'
       AND NOT EXISTS (SELECT 1 FROM kb.concept k
                        WHERE k.parent_code = c.code AND k.status <> 'отклонён')
    UNION ALL
    SELECT 'фактор без этапа', c.code, NULL
      FROM kb.concept c
     WHERE c.kind IN ('рудоконтролирующий фактор', 'условие наблюдения')
       AND c.parent_code IS NULL AND c.status <> 'отклонён'
    UNION ALL
    SELECT 'критерий без признаков', c.code, NULL
      FROM kb.concept c
     WHERE c.kind = 'критерий' AND c.status <> 'отклонён'
       AND NOT EXISTS (SELECT 1 FROM bridge.feature_concept b
                        WHERE b.concept_code = c.code AND b.status <> 'отклонён')
    UNION ALL
    SELECT 'признак без критерия', b.concept_code, f.code
      FROM bridge.feature_concept b
      JOIN data.feature f ON f.id = b.feature_id
      JOIN kb.concept c ON c.code = b.concept_code
     WHERE b.status = 'подтверждён' AND c.kind <> 'критерий'
       AND NOT EXISTS (SELECT 1 FROM bridge.feature_concept b2
                         JOIN kb.concept c2 ON c2.code = b2.concept_code
                        WHERE b2.feature_id = b.feature_id
                          AND c2.kind = 'критерий' AND b2.status <> 'отклонён');

COMMENT ON VIEW kb.concept_gap IS
    'Где предметная модель не достроена: фактор без критериев, критерий без признаков, признак без критерия';

GRANT SELECT ON kb.concept_tree, kb.concept_gap TO gis_read, gis_agent, gis_human;

