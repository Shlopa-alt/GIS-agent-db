-- -------------------------------------------------------- вид наружу (017)
-- Схема `api` показывает понятия наружу; с появлением уровней она должна
-- показывать и место понятия в дереве, иначе снаружи модель снова выглядит
-- плоским списком. Столбцы дописаны в конец: `CREATE OR REPLACE VIEW` иначе
-- откажется заменять представление.
CREATE OR REPLACE VIEW api.concept AS
    SELECT c.code AS понятие, c.kind AS вид, c.definition AS определение,
           c.source AS источник, c.confirmed_by AS подтвердил,
           c.parent_code AS выше, т.этап AS этап, т.признаков AS признаков
      FROM kb.concept c
      LEFT JOIN kb.concept_tree т ON т.понятие = c.code
     WHERE c.status = 'подтверждён';
