"""Общее для проверок: подключение к живой базе с одной попыткой на весь прогон.

Зачем. Проверки правил и панели идут на живой базе и пропускаются, когда её
нет, — так репозиторий собирается на чужой машине. Но каждая такая проверка
пробовала подключиться сама, и на машине без базы прогон упирался в отказ по
10 секунд двадцать пять раз: четыре с половиной минуты вместо двадцати секунд,
причём вся эта работа заведомо впустую. Непрерывная проверка при таком времени
бесполезна — поэтому недоступность базы выясняется один раз и запоминается.

Отказ кешируется, успех — нет: соединение каждой проверке нужно своё, со своей
транзакцией, которая потом откатывается.
"""

import pytest

psycopg = pytest.importorskip("psycopg")

from gisdb import db  # noqa: E402

#: Почему база недоступна, если это уже выяснилось. Пустая строка — доступна.
_причина: str | None = None


def соединение(роль: str):
    """Подключение к базе для проверки; база не поднята — проверка пропускается."""
    global _причина
    if _причина:
        pytest.skip(_причина)
    try:
        conn = db.connect(роль, connect_timeout=5)
    except Exception as беда:                      # база не поднята — не наш случай
        _причина = f"база недоступна ({роль}): {беда}"
        pytest.skip(_причина)
    _причина = ""
    return conn
