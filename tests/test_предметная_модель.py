"""Уровни предметной модели: этап процесса → фактор → критерий → признак.

Зачем эти проверки. Дерево понятий — не украшение схемы, а то, из чего
собирается объяснение участка карты. Разъехавшееся дерево ломает объяснение
молча: критерий под критерием или фактор без этапа не мешают ни одной записи
лечь в базу, зато запрос «чем обоснована эта клетка» начинает возвращать то
мусор, то пустоту — и не в день ошибки, а через месяц.

Правило порядка уровней живёт в базе (`kb.guard_concept_level`, миграция 018),
и здесь оно проверяется всеми способами, какими его можно сломать. Проверки
идут на живой базе и ничего в ней не меняют: каждая работает в своей
транзакции, которая откатывается.
"""

import pytest

from conftest import соединение  # noqa: E402  — одна попытка на весь прогон

#: Понятия, которые проверки заводят и откатывают. Имена заведомо не наши.
ЭТАП = "проба уровней: этап"
ФАКТОР = "проба уровней: фактор"
КРИТЕРИЙ = "проба уровней: критерий"


@pytest.fixture
def человек():
    conn = соединение("gis_human")
    проверить_миграцию(conn)
    yield conn
    conn.rollback()
    conn.close()


@pytest.fixture
def агент():
    conn = соединение("gis_agent")
    проверить_миграцию(conn)
    yield conn
    conn.rollback()
    conn.close()


def проверить_миграцию(conn) -> None:
    """Миграция 018 не накатана — проверять нечего, и это говорится прямо.

    Пропуск, а не отказ: файл схемы появляется в репозитории раньше, чем
    человек накатывает его на живую базу, — так и задумано. О самом отставании
    кричит `test_учёт_миграций_не_отстаёт`, дублировать его здесь незачем.
    """
    есть = conn.execute(
        """SELECT count(*) FROM information_schema.columns
            WHERE table_schema = 'kb' AND table_name = 'concept'
              AND column_name = 'parent_code'"""
    ).fetchone()[0]
    if not есть:
        pytest.skip("миграция 018_concept_level.sql не накатана: уровней модели ещё нет")


def завести(conn, код: str, вид: str, выше: str | None = None):
    conn.execute(
        """INSERT INTO kb.concept (code, kind, definition, parent_code)
           VALUES (%s, %s, 'запись проверки, откатывается', %s)""",
        (код, вид, выше),
    )


# ------------------------------------------------------- порядок уровней
def test_критерий_без_фактора_не_заводится(человек):
    """Критерий без того, что он проверяет, ничего не объясняет."""
    with pytest.raises(Exception, match="без фактора"):
        завести(человек, КРИТЕРИЙ, "критерий")


def test_критерий_не_становится_под_этап(человек):
    """Через уровень перескакивать нельзя: иначе фактор перестаёт быть нужен."""
    завести(человек, ЭТАП, "этап процесса")
    with pytest.raises(Exception, match="должен стоять фактор"):
        завести(человек, КРИТЕРИЙ, "критерий", ЭТАП)


def test_фактор_не_становится_под_фактор(человек):
    завести(человек, ЭТАП, "этап процесса")
    завести(человек, ФАКТОР, "рудоконтролирующий фактор", ЭТАП)
    with pytest.raises(Exception, match="только этап процесса"):
        завести(человек, ФАКТОР + " 2", "рудоконтролирующий фактор", ФАКТОР)


def test_этап_не_становится_под_этап(человек):
    завести(человек, ЭТАП, "этап процесса")
    with pytest.raises(Exception, match="верхний уровень"):
        завести(человек, ЭТАП + " 2", "этап процесса", ЭТАП)


def test_понятие_не_само_себе_выше(человек):
    with pytest.raises(Exception, match="под самим собой"):
        завести(человек, ЭТАП, "этап процесса", ЭТАП)


def test_вид_понятия_закрытый_список(человек):
    """Пятый уровень не заводится опечаткой: иначе он выпадет из всех запросов."""
    with pytest.raises(Exception, match="concept_kind_check"):
        завести(человек, ЭТАП, "этап процесса ")       # лишний пробел — уже не вид


# --------------------------------------------------------------- дерево
def test_дерево_сходится_от_критерия_до_этапа(человек):
    """Главное свойство: по критерию восстанавливается вся цепочка вверх."""
    завести(человек, ЭТАП, "этап процесса")
    завести(человек, ФАКТОР, "рудоконтролирующий фактор", ЭТАП)
    завести(человек, КРИТЕРИЙ, "критерий", ФАКТОР)
    этап, фактор, критерий = человек.execute(
        'SELECT этап, фактор, критерий FROM kb.concept_tree WHERE понятие = %s',
        (КРИТЕРИЙ,),
    ).fetchone()
    assert (этап, фактор, критерий) == (ЭТАП, ФАКТОР, КРИТЕРИЙ)


def test_пробелы_модели_видны_запросом(человек):
    """Фактор без критериев должен быть назван видом, а не замечен на показе."""
    завести(человек, ЭТАП, "этап процесса")
    завести(человек, ФАКТОР, "рудоконтролирующий фактор", ЭТАП)
    чего_нет = {с for (с,) in человек.execute(
        "SELECT чего_нет FROM kb.concept_gap WHERE понятие = %s", (ФАКТОР,)
    ).fetchall()}
    assert "фактор без критериев" in чего_нет
    assert "фактор без этапа" not in чего_нет, "этап у него как раз есть"


# --------------------------------------------------------------- агент
def test_агент_заводит_критерий_черновиком(агент):
    """Критерий — суждение, и агент имеет право его предложить."""
    этап = агент.execute(
        "SELECT code FROM kb.concept WHERE kind = 'этап процесса' LIMIT 1"
    ).fetchone()
    if not этап:
        pytest.skip("в базе нет ни одного этапа процесса")
    фактор = агент.execute(
        """SELECT code FROM kb.concept
            WHERE kind IN ('рудоконтролирующий фактор', 'условие наблюдения') LIMIT 1"""
    ).fetchone()[0]
    завести(агент, КРИТЕРИЙ, "критерий", фактор)
    статус = агент.execute(
        "SELECT status FROM kb.concept WHERE code = %s", (КРИТЕРИЙ,)
    ).fetchone()[0]
    assert статус == "черновик", "агент пишет черновик, а не готовое понятие"


def test_агент_не_подтверждает_критерий(агент):
    фактор = агент.execute(
        """SELECT code FROM kb.concept
            WHERE kind IN ('рудоконтролирующий фактор', 'условие наблюдения') LIMIT 1"""
    ).fetchone()[0]
    завести(агент, КРИТЕРИЙ, "критерий", фактор)
    with pytest.raises(Exception, match="только человек"):
        агент.execute(
            "UPDATE kb.concept SET status = 'подтверждён' WHERE code = %s", (КРИТЕРИЙ,)
        )


