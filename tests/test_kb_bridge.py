# --------------------------------------------------------- текст обоснования
def test_заглушка_уходит_а_вывод_агента_остаётся():
    было = ("Зоны каолинизации — вывод агента (уверенность: средняя, роль признака: прокси); "
            "публикация не привязана, база знаний в разработке.")
    стало = м.без_старого_блока(было)
    assert "публикация не привязана" not in стало
    assert стало.startswith("Зоны каолинизации")


def test_повторный_запуск_заменяет_блок_а_не_дописывает():
    ответы = [{"понятие": "гидротермальные изменения", "территория": "Билляхская зона",
               "метод": "ASTER", "откуда": "поиск по фрагментам",
               "фрагменты": [м.привести_находку(НАХОДКА, ("Билляхская зона", "ASTER"))]}]
    первый = "Смысл признака.\n\n" + м.блок(ответы)
    второй = м.без_старого_блока(первый) + "\n\n" + м.блок(ответы)
    assert второй == первый and второй.count(м.МЕТКА) == 1


def test_в_блоке_видно_откуда_ссылку_страницу_и_отбор():
    текст = м.блок([{"понятие": "гидротермальные изменения", "территория": None, "метод": None,
                     "откуда": "поиск по фрагментам",
                     "фрагменты": [м.привести_находку(НАХОДКА, (None, None))]}])
    assert "без отбора по территории и методу" in текст
    assert "doi:10.1/a" in текст and "с. 14" in текст
    assert "«Ранний калиевый метасоматизм" in текст and "и др." in текст


def test_пустой_ответ_тоже_ответ():
    текст = м.блок([{"понятие": "магматизм", "территория": None, "метод": None,
                     "откуда": "поиск по фрагментам", "фрагменты": []}])
    assert "ничего не нашлось" in текст


def test_отбор_по_территории_требует_упоминания_в_тексте():
    """Поиск смысловой: без этой проверки запись «отбор: Билляхская зона»
    стояла бы под статьёй про Египет — так и случилось в первом прогоне."""
    assert м.упоминает({"text": "В пределах Билляхской зоны известны…"}, "Билляхская зона")
    assert м.упоминает({"title": "Pyrite of the Khaptasynnakh zone, Anabar Shield",
                        "text": "На территории Анабарского щита…"}, "Анабарский щит")
    assert not м.упоминает({"text": "Abu Gaharish orogenic gold deposit, Egypt"},
                           "Билляхская зона")
