"""Мост к базе знаний: отбор источников, лестница запросов, текст обоснования.

Обращения по сети проверены отдельно (`test_kb_client.py`), поэтому база знаний
здесь — заглушка с теми же двумя методами: `поиск` и `датасет`. Так видно само
правило отбора: граф, если он знает понятие, иначе поиск по фрагментам.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))

import db_kb_evidence as м  # noqa: E402

НАХОДКА = {
    "doc_id": "10.1_a", "doi": "10.1/a", "title": "Гидротермальные изменения зоны",
    "year": 2021, "authors": ["Иванов И.И.", "Петров П.П.", "Сидоров С.С."],
    "journal": "Руды и металлы", "url": "https://x/a.pdf", "pages": [14],
    "text": "Ранний калиевый метасоматизм сменяется окварцеванием.",
    "similarity": 0.71, "found_by": "оба",
}
ФАКТ = {
    "relation": "контролируется", "other": "Билляхская зона", "kind": "структура",
    "documents": 2, "fragments": 3,
    "quotes": [{"quote": "Оруденение контролируется Билляхской зоной.", "doc_id": "10.9_z",
                "title": "Тектоно-флюидитные зоны", "year": 2024, "url": "https://x/z",
                "chunk_id": 11, "pages": [27], "doi": "10.9/z"}],
}


class Заглушка:
    """База знаний: граф знает «Билляхскую зону», а поиск находит только при
    ослабленном отборе — по территории без метода."""

    def __init__(self, с_графом: bool = False):
        self.с_графом = с_графом
        self.запросы: list[str] = []
        self.пометки: list[str] = []

    def поиск(self, запрос, предел=10, мин_близость=0.5, на_статью=1, **_):
        self.запросы.append(запрос)
        return [] if "ASTER" in запрос else [НАХОДКА]

    def датасет(self, имя):
        if not self.с_графом:
            raise м.kb_client.НетЯкоря(имя, ["Анабарский щит"])
        return {"name": имя, "facts": [ФАКТ], "documents": 2, "includes": []}


# -------------------------------------------------------------------- отбор
def test_отбор_от_строгого_к_мягкому():
    assert м.варианты(("Билляхская зона", "Анабарский щит"), "ASTER") == [
        ("Билляхская зона", "ASTER"), ("Билляхская зона", None),
        ("Анабарский щит", "ASTER"), ("Анабарский щит", None),
        (None, "ASTER"), (None, None),
    ]


def test_без_метода_лишних_вариантов_нет():
    assert м.варианты(("Анабарский щит",), None) == [("Анабарский щит", None), (None, None)]


def test_запрос_не_тащит_оговорки_про_наш_проект():
    определение = ("Формы рельефа и их производные. Косвенно отражают устойчивость пород. "
                   "Но в этом проекте высота даёт около половины сигнала прогноза.")
    текст = м.запрос("рельеф и геоморфология", определение, "Анабарский щит", None)
    assert "в этом проекте" not in текст
    assert текст.startswith("рельеф и геоморфология") and текст.endswith("Анабарский щит")


def test_лестница_доходит_до_сработавшего_отбора():
    """Находка не про нашу территорию — лестница доходит до «без отбора», и
    именно это записывается при цитате."""
    знания = Заглушка()
    фрагменты = м.из_поиска(знания, "гидротермальные изменения", "Околорудные изменения.",
                            "ASTER", ("Билляхская зона",), 3)
    assert len(фрагменты) == 1
    assert "ASTER" in знания.запросы[0], "сначала спрашиваем узко"
    assert (фрагменты[0]["территория"], фрагменты[0]["метод"]) == (None, None)


def test_находка_про_нашу_территорию_отбор_сохраняет():
    знания = Заглушка()
    знания.поиск = lambda запрос, **_: [{**НАХОДКА, "text": "В пределах Билляхской зоны…"}]
    фрагменты = м.из_поиска(знания, "структурный контроль", "Разломы.", None,
                            ("Билляхская зона",), 3)
    assert фрагменты[0]["территория"] == "Билляхская зона"


