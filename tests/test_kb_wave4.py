# -------------------------------------------------------------------- снимок
def test_первый_снимок_сравнивать_не_с_чем():
    assert "первый" in с.сравнение(None, {"статей": 10})


def test_снимок_видит_рост_корпуса():
    прошлый = {"когда": datetime(2026, 10, 23, 23, 35, tzinfo=timezone.utc),
               "статей": 2052, "фактов": 203173, "версия": "34f5360"}
    текст = с.сравнение(прошлый, {"статей": 2100, "фактов": 203173, "версия": "34f5360"})
    assert "2052 → 2100 (+48)" in текст and "фактов" not in текст


def test_тот_же_корпус_перезапуск_не_нужен():
    прошлый = {"когда": datetime(2026, 10, 23, 23, 35, tzinfo=timezone.utc),
               "статей": 2052, "фактов": 1, "версия": "a"}
    assert "перезапуск ничего не даст" in с.сравнение(
        прошлый, {"статей": 2052, "фактов": 1, "версия": "a"})
