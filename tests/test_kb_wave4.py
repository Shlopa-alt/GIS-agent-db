# --------------------------------------------------------------------- обмен
def _ц(статус, близость):
    return {"статус": статус, "близость": близость}


def test_замер_без_решений_честно_пуст():
    assert "нечего" in о.замер_порога([])["вывод"]


def test_замер_различает_когда_принятые_выше():
    з = о.замер_порога([_ц("подтверждён", 0.68), _ц("подтверждён", 0.66),
                        _ц("отклонён", 0.58), _ц("отклонён", 0.59)])
    assert з["различение"] == 1.0 and "различает" in з["вывод"]


def test_замер_видит_бесполезность_порога():
    з = о.замер_порога([_ц("подтверждён", 0.60), _ц("подтверждён", 0.66),
                        _ц("отклонён", 0.68), _ц("отклонён", 0.61)])
    assert з["различение"] == 0.25 and "не различает" in з["вывод"]


