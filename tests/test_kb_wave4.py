def _сущность(имя, статей=3, фактов=10, написания=()):
    return {"имя": имя, "статей": статей, "фактов": фактов, "вид": "структура",
            "написания": list(написания)}


# --------------------------------------------------------------------- якоря
def test_основа_ловит_слово_с_начала():
    assert я.совпадение(_сущность("дайки долеритов"), ("дайк",)) == "дайк"
    assert я.совпадение(_сущность("shear zones"), ("shear zone",)) == "shear zone"
    assert я.совпадение(_сущность("прадайка"), ("дайк",)) is None


def test_основа_ищется_и_в_написаниях():
    с_ = _сущность("сдвиговая зона", написания=["Shear Zone"])
    assert я.совпадение(с_, ("shear zone",)) == "shear zone"


def test_одна_статья_не_якорь_по_умолчанию():
    """Двадцать фактов из одной статьи подтвердить нечем — то же правило у
    самой базы знаний."""
    сущности = [_сущность("разлом X", статей=1, фактов=50), _сущность("разломы", статей=4)]
    assert [с_["имя"] for с_ in я.подобрать(сущности, ("разлом",), 5, 2)] == ["разломы"]


def test_статьи_важнее_фактов():
    сущности = [_сущность("fault A", статей=2, фактов=90),
                _сущность("faults", статей=8, фактов=20)]
    assert [с_["имя"] for с_ in я.подобрать(сущности, ("fault",), 5, 2)] == ["faults", "fault A"]


def test_у_каждого_понятия_базы_есть_основы_и_связи():
    """Основы выписаны под все понятия, кроме критериев; связи — из закрытого
    списка базы знаний."""
    допустимые = {"входит в", "сложено", "локализовано в", "контролируется", "содержит",
                  "ассоциирует с", "сопровождается", "генетически связано с",
                  "образовано при", "указывает на", "выявлено методом", "пересекает",
                  "сменяется", "относится к"}
    assert len(я.ОСНОВЫ) == 11
    for связи in я.СВЯЗИ_ПО_РОДУ.values():
        assert set(связи) <= допустимые


def test_территория_находится_по_имени():
    сущности = [_сущность("Анабарский щит", статей=6), _сущность("Билляхская зона", статей=2),
                _сущность("гранит")]
    assert [с_["имя"] for с_ in я.территория(сущности)] == ["Анабарский щит", "Билляхская зона"]


def test_запасной_запрос_без_оговорок_проекта():
    з = я.запасной_запрос("рельеф и геоморфология",
                          "Формы рельефа и их производные. В этом проекте высота даёт половину.")
