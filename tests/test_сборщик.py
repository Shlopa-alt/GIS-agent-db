"""Агент-сборщик (узел 3): осмотр ничего не меняет и называет расхождения.

Главное свойство сборщика — он только смотрит. Осмотр, который что-то правит,
нельзя запускать по расписанию, а именно для этого он и нужен.
"""

import importlib
import sys
from pathlib import Path

import pytest

from conftest import соединение  # noqa: E402

КОРЕНЬ = Path(__file__).resolve().parents[1]


def сборщик():
    sys.path.insert(0, str(КОРЕНЬ / "scripts"))
    return importlib.import_module("db_collector")


@pytest.fixture
def читатель():
    conn = соединение("gis_read")
    yield conn
    conn.rollback()
    conn.close()


def test_запросы_сборщика_работают_на_живой_базе(читатель):
    """Запрос, который молча не выполняется, превращает осмотр в пустую опись."""
    с = сборщик()
    for имя in ("СОСТАВ", "СЛОИ", "ГРУППЫ", "ФОРМУЛА", "ПУТИ", "СЕТКИ"):
        запрос = getattr(с, имя)
        if "{где}" in запрос:
            запрос = запрос.format(где="")
        читатель.execute(запрос).fetchall()


def test_осмотр_читает_и_не_пишет(читатель):
    """Сборщик работает ролью агента, но сам данные не меняет: права читателя
    достаточно для всех его запросов — это и есть проверка, что он только смотрит."""
    с = сборщик()
    пути = читатель.execute(с.ПУТИ).fetchall()
    assert all(ссылка.startswith(("проект:/", "хранилище:/")) or "/" in ссылка
               for _, ссылка in пути), "путь слоя записан абсолютным — при переезде он ложен"


def test_ссылка_на_файл_проекта_разрешается():
    """Ссылка «проект:/…» должна вести в репозиторий прогноза, а не базы.

    Первый осмотр нашёл 33 «пропавших» слоя: префикс «проект» разрешался в
    каталог самой базы, где данных нет и не бывает. Слои при этом лежали на
    месте — ложной была ссылка, а не данные.
    """
    from gisdb import db

    ссылка = db.store_ref(db.КОРЕНЬ_ПРОЕКТА / "data" / "processed" / "x.parquet")
    assert ссылка == "проект:/data/processed/x.parquet"
    assert db.store_path(ссылка) == db.КОРЕНЬ_ПРОЕКТА / "data" / "processed" / "x.parquet"
    assert db.КОРЕНЬ_ПРОЕКТА != db.PROJECT_ROOT, \
        "корень прогноза и корень репозитория базы — разные каталоги"


def test_выгрузка_каналов_не_считается_новым_сырьём(читатель):
    """Иначе каждый осмотр зовёт регистрировать то, что уже зарегистрировано."""
    from gisdb import db

    с = сборщик()
    if not db.КОРЕНЬ_ПРОЕКТА.is_dir():
        pytest.skip("репозитория прогноза нет рядом")
    новое, выгрузки = с.лишние(читатель)
    assert all("__" not in Path(п).stem for п in новое)
    assert all("__" in Path(п).stem for п in выгрузки)


def test_признаки_не_ссылаются_на_незаведённую_сетку(читатель):
    """Признак с именем несуществующей сетки выпадает из всех запросов по территории.

    Так и было четыре недели: прогон #1 подписал 105 признаков основного листа
    именем соседнего (`лист-R-49-I-II-500м`), загрузчик потом исправили, а строки
    остались. В описи у основного листа стояло «кодов признаков 0» при 2,2 млн
    значений, и ничего не падало. Чинит миграция 020.
    """
    с = сборщик()
    ничьи = читатель.execute(с.СЕТКИ).fetchall()
    assert not ничьи, (
        "признаки ссылаются на сетку, которой нет в data.grid: "
        + ", ".join(f"{имя} ({сколько} кодов)" for имя, сколько in ничьи)
        + ". Накатить: python db/migrate.py")


def test_значения_признака_лежат_на_его_сетке(читатель):
    """Имя сетки в признаке и сетка его ячеек должны совпадать.

    Проверка сильнее предыдущей: имя может указывать на заведённую сетку и всё
    равно не на ту, где лежат значения. Тогда «что собрано по территории»
    отвечает уверенно и неверно.
    """
    расхождения = читатель.execute(
        """SELECT f.code, f.definition->>'сетка', g.code, count(*)
             FROM data.feature_value v
             JOIN data.feature f ON f.id = v.feature_id
             JOIN data.cell c ON c.id = v.cell_id
             JOIN data.grid g ON g.id = c.grid_id
            WHERE g.code <> f.definition->>'сетка'
            GROUP BY 1, 2, 3 LIMIT 5"""
    ).fetchall()
    assert not расхождения, (
        "значения признака лежат не на той сетке, что названа в его сборке: "
        + "; ".join(f"{код}: названа {названа}, значения на {где} ({сколько})"
                    for код, названа, где, сколько in расхождения))
