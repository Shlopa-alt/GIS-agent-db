"""Сеансы панели: учётная запись — это роль базы, а не имя в печенье.

Как было. Панель спрашивала имя и писала его в печенье на год; это имя шло
подписью под решением. Подписать решение чужим именем мог любой, кто открыл
страницу, — а подпись человека под паспортом и есть главное, что хранит база.
Пароля не было вовсе: защитой служило то, что сервер слушает только петлевой
адрес. На одной машине это терпимо, на сервере — нет.

Как стало. Учётная запись проверяющего — роль Postgres с паролем. Панель
проверяет пароль единственным способом, который ничего не изобретает: пробует
открыть соединение этой ролью. Удалось — пароль верен, и дальше все запросы
идут от имени этой роли. Значит:

* своего хранилища паролей у панели нет, и утечь из неё нечему;
* право вынести вердикт даёт членство в `gis_confirmer` — его проверяет
  триггер самой базы, а не наша страница. Читатель увидит очередь и карточки,
  но его UPDATE отклонит база, а не вежливость шаблона;
* `confirmed_by` и подпись в журнале заполняются именем роли, то есть тем, под
  кем человек вошёл. Подписаться чужим именем больше нельзя.

Пароль живёт в памяти процесса, пока жив сеанс, и нигде не записывается:
соединение к базе приходится открывать на каждый запрос. Печенье хранит только
случайный ключ сеанса — из него ни имя, ни пароль не восстановить.

Сеанс гаснет через 12 часов и при остановке процесса. Это осознанно: панель —
рабочее место на день, а не служба с постоянным входом.
"""

from __future__ import annotations

import secrets
import time
from dataclasses import dataclass, field

from gisdb import db

#: Имя печенья — латиницей: протокол другого не принимает (http.cookies).
ПЕЧЕНЬЕ = "panel_session"

#: Сколько живёт сеанс без обращений, секунды.
СРОК = 12 * 3600


@dataclass
class Сеанс:
    """Кто вошёл и чем он уполномочен. Пароль — только в памяти процесса."""

    роль: str
    пароль: str = field(repr=False)
    может_решать: bool
    открыт: float = field(default_factory=time.monotonic)
    последнее: float = field(default_factory=time.monotonic)

    def жив(self) -> bool:
        return time.monotonic() - self.последнее < СРОК


#: Ключ печенья → сеанс. В памяти процесса: перезапуск панели всех выгоняет.
СЕАНСЫ: dict[str, Сеанс] = {}


class НеВошёл(Exception):
    """Сеанса нет, истёк или был снят. Страница отвечает перенаправлением."""


def _убрать_истёкшие() -> None:
    for ключ in [к for к, с in СЕАНСЫ.items() if not с.жив()]:
        СЕАНСЫ.pop(ключ, None)


def войти(роль: str, пароль: str) -> str:
    """Проверить пароль, открыв соединение, и завести сеанс. Вернуть ключ.

    Ошибку подключения наружу не пересказываем: сообщения Postgres различают
    «нет такой роли» и «пароль не подходит», а это подсказка подбирающему.
    """
    роль = роль.strip()
    if not роль or not пароль:
        raise НеВошёл("нужны имя учётной записи и пароль")
    try:
        with db.connect(роль, пароль=пароль, connect_timeout=5) as conn:
            может = conn.execute(
                "SELECT pg_has_role(current_user, 'gis_confirmer', 'MEMBER')"
            ).fetchone()[0]
    except Exception as беда:                                   # noqa: BLE001
        if "password" in str(беда).lower() or "role" in str(беда).lower():
            raise НеВошёл("имя или пароль не подходят") from беда
        raise НеВошёл(f"база недоступна: {беда}") from беда
    _убрать_истёкшие()
    ключ = secrets.token_urlsafe(32)
    СЕАНСЫ[ключ] = Сеанс(роль=роль, пароль=пароль, может_решать=bool(может))
    return ключ


def сеанс(ключ: str | None) -> Сеанс:
    """Сеанс по ключу печенья; нет или истёк — `НеВошёл`."""
    с = СЕАНСЫ.get(ключ or "")
    if с is None:
        raise НеВошёл("сеанс не найден: войдите заново")
    if not с.жив():
        СЕАНСЫ.pop(ключ or "", None)
        raise НеВошёл("сеанс истёк: войдите заново")
    с.последнее = time.monotonic()
    return с


def выйти(ключ: str | None) -> None:
    СЕАНСЫ.pop(ключ or "", None)
