"""Ссылка на репозиторий прогноза — только для загрузчиков, не для ядра.

Признаки, которые паспортизует база, считаются в проекте прогноза (`GIS`),
и оттуда же взяты эталонные предметные формулировки. Но **ядро базы проекта
не требует**: панель, сбор фактов и паспортизатор работают, когда рядом нет
ничего, кроме базы. Проверяется это проверкой `tests/test_независимость.py`.

Граница такая:

* **загрузчики** (`scripts/db_load_dictionary.py`, `db_fill_checks.py`,
  `db_register_layers.py`) читают проект через этот модуль. Они переносят в
  базу то, что посчитано в проекте, вместе с отпечатком источника;
* **ядро** (`gisdb/`) читает только базу. Словарь признаков лежит снимком в
  `meta.feature_term`, расчёты — в `meta.feature_check`.

Так знание остаётся в одном месте — словарь по-прежнему единственный, в
проекте, — а база перестаёт быть приложением к исследовательскому
репозиторию. Отстал ли снимок, говорит сверка отпечатка:
`python scripts/db_load_dictionary.py --проверить`.

Путь задаётся переменной `GIS_PROJECT_ROOT`; по умолчанию проект ищется
соседним каталогом `GIS`. Пакеты у репозиториев разные (`gisdb` и `src`),
поэтому добавление проекта в путь поиска ничего не перекрывает.

    from gisdb.project import подключить
    подключить()
    from src.feature_dict import describe       # уже из проекта
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

КОРЕНЬ = Path(os.environ.get(
    "GIS_PROJECT_ROOT", Path(__file__).resolve().parents[2] / "GIS"))


def подключить() -> Path:
    """Сделать модули и данные проекта доступными; вернуть его корень."""
    if not (КОРЕНЬ / "src").is_dir():
        raise RuntimeError(
            f"репозиторий проекта не найден: {КОРЕНЬ}. Укажите его переменной "
            "GIS_PROJECT_ROOT — оттуда берутся данные признаков и словарь"
        )
    if str(КОРЕНЬ) not in sys.path:
        sys.path.insert(0, str(КОРЕНЬ))
    return КОРЕНЬ
