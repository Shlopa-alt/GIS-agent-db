"""Обращение к базе знаний статей — единственная точка выхода на другую машину.

База знаний (репозиторий `georag`) стоит на отдельном компьютере в той же сети
и отвечает своим веб-интерфейсом. Ходим только мы и только за чтением: обратной
связи нет, база знаний об этой базе данных не знает и адресов её не хранит.

Адрес — переменная `GIS_KB_URL`, по умолчанию `http://localhost:8000`. На другой
машине он остаётся тем же: туннель подставляет её порт на наш, поэтому ни
адресов, ни имён компьютеров в коде нет.

    ssh -N -L 8000:127.0.0.1:8000 <пользователь>@<машина базы знаний>

**Куда обращаться и почему не как раньше.** Прежний мост спрашивал
`/api/concept` и `/api/concepts` — словарь понятий базы знаний. Такого словаря
там больше нет: знание лежит типизированным графом фактов (9 видов концов,
14 связей, за каждым фактом дословная цитата), и спрашивать надо его:

    /api/datasets           какие сущности есть — словарь имён графа (не
                            завершается на большом графе, см. `имена()`)
    /api/network            граф целиком: сущности с числами фактов и статей
    /api/dataset?name=…     факты о сущности: связь, второй конец, цитаты
    /api/search?q=…         фрагменты статей по смыслу и по словам, со страницами
    /api/document?doc_id=…  разобранная статья фрагментами
    /api/figure?id=…        рисунок статьи — двоичный ответ, не JSON
    /api/health             чем отвечала база: версия, модель, объём

**Неполный ответ — видимый ответ.** Три вещи появляются на той машине только
после отправленных туда правок: номера страниц и DOI у цитат графа, сам
`/api/health` и фильтр по статье в поиске. Пока их нет, клиент не падает и не
подменяет данные: он возвращает пометки («страницы нет», «версия неизвестна»,
«фильтр по статье сделан на нашей стороне»), и они уходят в журнал прогона.
Прогон должен быть видно неполным, а не молча неверным.
"""

from __future__ import annotations

import json
import os
import socket
import urllib.error
import urllib.parse
import urllib.request

АДРЕС: str = os.environ.get("GIS_KB_URL", "http://localhost:8000")
ТАЙМАУТ: int = 60

#: Сколько ждать словарь имён графа. Его обработчик на той машине перебирает
#: граф целиком для каждой сущности и на 45 тысячах сущностей не укладывается и
#: в час (разбор — План-волна-4.md). Ждать его минуту и повторять — значит
#: потерять две минуты и получить ложный совет про туннель.
ТАЙМАУТ_ИМЁН: int = 10

#: Что делать, если база знаний молчит. Подсказка общая; причину называет
#: `диагноз()` — три поломки выглядят одинаково, а лечатся по-разному.
ПОДСКАЗКА = (
    "база знаний не ответила. На её машине должен работать «python georag.py web», "
    "а на этой — туннель «ssh -N -L 8000:127.0.0.1:8000 <пользователь>@<машина>»"
)


ТУННЕЛЬ = ("«python scripts/kb_tunnel.py» (ssh -N -L 8000:127.0.0.1:8000 "
           "<пользователь>@<машина>)")


def диагноз(сбой: BaseException | None, при_соединении: bool = False) -> str:
    """Какая из трёх поломок случилась — по тому, как именно оборвалась связь.

    * в соединении отказано — на нашей стороне порт никто не слушает: туннель
      не поднят. На Windows отказ приходит не сразу, а после повторов, и при
      коротком сроке выглядит истечением срока — поэтому срок, истёкший ещё
      при установке соединения, толкуется так же;
    * соединение принято и закрыто без ответа — туннель стоит, но на той машине
      порт 8000 никто не слушает: сервер базы знаний не запущен (ssh принимает
      соединение сам и закрывает его, когда не может пробросить дальше);
    * ответа нет дольше срока — сервер жив, но этот запрос не завершается.
    """
    текст = str(сбой or "")
    отказ = (isinstance(сбой, ConnectionRefusedError) or "10061" in текст
             or "refused" in текст)
    срок = isinstance(сбой, (socket.timeout, TimeoutError)) or "timed out" in текст
    if отказ or (срок and при_соединении):
        return ("туннель не поднят: на этой машине порт базы знаний никто не слушает — "
                + ТУННЕЛЬ)
    if срок:
        return ("сервер принял запрос, но не ответил в срок: связь есть, "
                "медленный или зависший обработчик на той стороне")
    if "closed connection without response" in текст or isinstance(
            сбой, (ConnectionResetError, ConnectionAbortedError)):
        return ("туннель стоит, но сервер базы знаний на той машине не запущен — "
                "там нужен «python georag.py web»")
    return ПОДСКАЗКА


class НетСвязи(RuntimeError):
    """База знаний не ответила — дальше идти бессмысленно."""


class ОшибкаЗапроса(ValueError):
    """База знаний ответила отказом и объяснила, чем он вызван.

    Тело отказа несёт `error`, иногда `detail` и список известных имён `known` —
    он и есть словарь, по которому подбирается якорь понятия.
    """

    def __init__(self, ответ: dict, код: int):
        super().__init__(ответ.get("error") or f"база знаний ответила {код}")
        self.ответ, self.код = ответ, код
        self.известные: list[str] = list(ответ.get("known") or [])


class НетЯкоря(LookupError):
    """В графе базы знаний нет такой сущности; известные имена — в `известные`.

    Это не сбой, а содержательный ответ: понятию нечего сопоставить, и так и
    надо записать, а не подбирать запрос, пока что-нибудь не найдётся.
    """

    def __init__(self, имя: str, известные: list[str] | None = None):
        super().__init__(f"в фактах из статей нет: {имя}")
        self.имя = имя
        self.известные = известные or []


class БазаЗнаний:
    """Клиент к базе знаний. Создаётся один раз на прогон: в нём живут пометки
    о том, чего эта база ещё не умеет, и они нужны все сразу, в конце."""

    def __init__(self, адрес: str = АДРЕС, таймаут: int = ТАЙМАУТ):
        self.адрес = адрес.rstrip("/")
        self.таймаут = таймаут
        self.пометки: list[str] = []

    # ------------------------------------------------------------- обращения
    def _получить(self, путь: str, параметры: dict | None = None,
                  таймаут: int | None = None, попыток: int = 2) -> tuple[bytes, str]:
        """Байты ответа и тип содержимого. Одна повторная попытка: беспроводная
        сеть роняет соединение чаще, чем падает сам сервер."""
        адрес = self.адрес + путь
        if параметры:
            адрес += "?" + urllib.parse.urlencode(
                {к: з for к, з in параметры.items() if з is not None}
            )
        последняя: BaseException | None = None
        при_соединении = False
        for попытка in range(1, попыток + 1):
            try:
                with urllib.request.urlopen(адрес, timeout=таймаут or self.таймаут) as ответ:
                    return ответ.read(), ответ.headers.get("Content-Type", "")
            except urllib.error.HTTPError:
                # Ответ сервера — это ответ, повторять нечего: разбирают выше.
                raise
            except (urllib.error.URLError, socket.timeout, ConnectionError) as сбой:
                # URLError оборачивает только сбои установки соединения; срок,
                # истёкший при чтении ответа, приходит голым TimeoutError.
                при_соединении = isinstance(сбой, urllib.error.URLError)
                последняя = getattr(сбой, "reason", None) or сбой
                if попытка == попыток:
                    break
        raise НетСвязи(f"{диагноз(последняя, при_соединении)}. Причина: {последняя}") \
            from последняя

    def _json(self, путь: str, параметры: dict | None = None,
              таймаут: int | None = None, попыток: int = 2) -> dict:
        try:
            тело, _ = self._получить(путь, параметры, таймаут, попыток)
        except urllib.error.HTTPError as сбой:
            ответ = _разобрать(сбой.read())
            if сбой.code == 404:
                raise НетСвязи(
                    f"у базы знаний нет адреса {путь} — на её машине не применены "
                    "правки из инструкции"
                ) from сбой
            raise ОшибкаЗапроса(ответ, сбой.code) from сбой
        return _разобрать(тело)

    # -------------------------------------------------------------- что там
    def состояние(self) -> dict:
        """Чем отвечает база знаний: объём, модель векторов, версия кода.

        Это происхождение цитаты: через полгода надо знать, по какой разметке
        она получена. Нет `/api/health` — берём то, что есть у `/api/stats`, и
        помечаем ответ неполным.
        """
        try:
            ответ = self._json("/api/health")
            return {
                "статей": ответ.get("documents"),
                "фрагментов": ответ.get("chunks"),
                "с_векторами": ответ.get("embedded"),
                "фактов": (ответ.get("facts") or {}).get("facts"),
                "модель": ответ.get("embed_model") or "",
                "версия": ответ.get("version") or "",
                # Время разметки той базы — им помечается каждая цитата. Раньше
                # ключа не было, и мост писал в kb_as_of пустоту.
                "проверено": ответ.get("checked_at"),
                "полное": True,
            }
        except НетСвязи as сбой:
            if "нет адреса" not in str(сбой):
                raise
        ответ = self._json("/api/stats")
        self._пометить("версия базы знаний неизвестна: адреса /api/health ещё нет")
        return {
            "статей": ответ.get("documents"),
            "фрагментов": ответ.get("chunks"),
            "с_векторами": None,
            "фактов": None,
            "модель": "",
            "версия": "",
            "проверено": None,
            "полное": False,
        }

    def граф(self) -> list[dict]:
        """Все сущности графа с числами: имя, фактов, статей, вид, написания.

        Берётся из `/api/network` — граф целиком за полторы секунды. Ответ
        тяжёлый (десятки мегабайт: связи идут с цитатами), но это единственный
        обработчик, который отдаёт полный словарь имён и при этом завершается.
        Числа у сущности — по ней самой, без родственников («зона Персияновского
        разлома» не входит в «Персияновский разлом»), в отличие от карточки
        `/api/dataset`.
        """
        ответ = self._json("/api/network")
        сущности = []
        for узел in ответ.get("nodes") or []:
            if узел.get("kind") == "статья":
                continue
            сущности.append({
                "имя": узел.get("name") or "",
                "фактов": int(узел.get("facts") or 0),
                "статей": int(узел.get("documents") or 0),
                "вид": узел.get("category") or "",
                "написания": list(узел.get("spellings") or []),
            })
        return сущности

    def имена(self, предел: int = 300) -> list[str]:
        """Словарь имён графа — то, чему вообще можно сопоставить понятие.

        Сперва короткая попытка `/api/datasets`; молчит — имена из
        `/api/network`, самые богатые фактами первыми, и пометка в журнал. Это
        не сбой связи: туннель и сервер работают, не завершается один
        обработчик, и советовать проверить туннель здесь было бы неправдой.
        """
        try:
            ответ = self._json("/api/datasets", таймаут=ТАЙМАУТ_ИМЁН, попыток=1)
            return [с["name"] for с in (ответ.get("datasets") or [])][:предел]
        except НетСвязи as сбой:
            if "не ответил в срок" not in str(сбой):
                raise
        self._пометить("словарь имён графа (/api/datasets) не отвечает — "
                       "имена взяты из /api/network")
        сущности = sorted(self.граф(), key=lambda с: (-с["фактов"], с["имя"]))
        return [с["имя"] for с in сущности][:предел]

    def датасет(self, имя: str) -> dict:
        """Все факты о сущности: связь, второй конец и его вид, цитаты, статьи."""
        try:
            return self._json("/api/dataset", {"name": имя})
        except ОшибкаЗапроса as сбой:
            # Отказ несёт список известных имён — по нему и подбирается якорь.
            raise НетЯкоря(имя, сбой.известные) from сбой

    def поиск(
        self,
        запрос: str,
        предел: int = 10,
        мин_близость: float = 0.5,
        на_статью: int = 1,
        статья: str | None = None,
        с_года: int | None = None,
    ) -> list[dict]:
        """Фрагменты статей по запросу. `статья` — искать только в её границах.

        Фильтр по статье в базе знаний есть, но через её интерфейс передаётся
        только после правок. Поэтому ответ проверяется: пришло чужое — отбираем
        сами и записываем, что фильтр сработал на нашей стороне. Своей
        проверки мало для точности выдачи (места в списке считались по всей
        базе), и это тоже надо видеть.
        """
        ответ = self._json(
            "/api/search",
            {
                "q": запрос,
                "limit": предел,
                "per_doc": на_статью,
                "min_similarity": мин_близость,
                "year_from": с_года,
                "doc_id": статья,
            },
        )
        фрагменты = ответ.get("hits") or []
        if статья:
            свои = [ф for ф in фрагменты if ф.get("doc_id") == статья]
            if len(свои) != len(фрагменты):
                self._пометить(
                    "поиск в границах статьи сделан на нашей стороне: база знаний "
                    "параметр doc_id не приняла"
                )
            фрагменты = свои
        return фрагменты

    def рисунок(self, номер: int) -> bytes:
        """Картинка рисунка статьи. Ответ двоичный, поэтому не через `_json`."""
        тело, тип = self._получить("/api/figure", {"id": номер})
        if not тип.startswith("image/"):
            raise ValueError(f"рисунка {номер} нет: база знаний ответила {тип or 'без типа'}")
        return тело

    # ------------------------------------------------------------- пометки
    def _пометить(self, текст: str) -> None:
        if текст not in self.пометки:
            self.пометки.append(текст)


def _разобрать(тело: bytes) -> dict:
    try:
        ответ = json.loads(тело.decode("utf-8") or "{}")
    except (UnicodeDecodeError, json.JSONDecodeError) as сбой:
        raise ValueError(f"база знаний ответила не JSON: {сбой}") from сбой
    return ответ if isinstance(ответ, dict) else {"ответ": ответ}


def страница(фрагмент: dict) -> int | None:
    """Первая страница фрагмента или цитаты. Нет страниц — None, и это честный
    ответ: у цитат графа они появляются только после правок на той машине."""
    страницы = фрагмент.get("pages") or []
    return int(страницы[0]) if страницы else None


def ссылка_на_страницу(фрагмент: dict) -> str:
    """Ссылка, по которой человек открывает именно ту страницу, если это PDF."""
    адрес = фрагмент.get("url") or ""
    н = страница(фрагмент)
    return f"{адрес}#page={н}" if адрес.lower().endswith(".pdf") and н else адрес
