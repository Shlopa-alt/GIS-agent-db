"""Снимок состояния базы знаний: что было на той стороне в момент обращения.

Пишется каждым скриптом, который ходит к базе знаний, в `meta.kb_snapshot`
(миграция 021) и сравнивается с прошлым снимком. Отсюда ответ «стоит ли
перезапускать мост» и происхождение каждой цитаты.
"""

from __future__ import annotations

ПРОШЛЫЙ = """
SELECT taken_at, documents, chunks, facts, entities, version, checked_at
  FROM meta.kb_snapshot
 ORDER BY taken_at DESC, id DESC
 LIMIT 1
"""


def записать(conn, состояние: dict, script: str, run_id: int | None = None,
             сущностей: int | None = None, note: str | None = None) -> dict | None:
    """Записать снимок и вернуть прошлый (до этого) — для сравнения.

    Прошлый читается до вставки: иначе сравнивали бы снимок сам с собой.
    """
    строка = conn.execute(ПРОШЛЫЙ).fetchone()
    прошлый = dict(zip(("когда", "статей", "фрагментов", "фактов", "сущностей",
                        "версия", "проверено"), строка)) if строка else None
    conn.execute(
        """INSERT INTO meta.kb_snapshot
               (run_id, script, documents, chunks, embedded, facts, entities,
                embed_model, version, checked_at, complete, note)
           VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)""",
        (run_id, script, состояние.get("статей"), состояние.get("фрагментов"),
         состояние.get("с_векторами"), состояние.get("фактов"), сущностей,
         состояние.get("модель") or None, состояние.get("версия") or None,
         состояние.get("проверено"), bool(состояние.get("полное")), note),
    )
    return прошлый


def сравнение(прошлый: dict | None, состояние: dict) -> str:
    """Одна строка для человека: подрос ли корпус с прошлого обращения."""
    if прошлый is None:
        return "снимок первый — сравнивать не с чем"
    когда = прошлый["когда"].strftime("%d.%m.%Y %H:%M")
    сдвиги = []
    for ключ, подпись in (("статей", "статей"), ("фактов", "фактов в графе")):
        было, стало = прошлый.get(ключ), состояние.get(ключ)
        if было is not None and стало is not None and стало != было:
            сдвиги.append(f"{подпись} {было} → {стало} ({стало - было:+d})")
    if прошлый.get("версия") and состояние.get("версия") and \
            прошлый["версия"] != состояние["версия"]:
        сдвиги.append(f"код {прошлый['версия']} → {состояние['версия']}")
    if not сдвиги:
        return f"с прошлого снимка ({когда}) база знаний та же — перезапуск ничего не даст"
    return f"с прошлого снимка ({когда}): " + "; ".join(сдвиги)
